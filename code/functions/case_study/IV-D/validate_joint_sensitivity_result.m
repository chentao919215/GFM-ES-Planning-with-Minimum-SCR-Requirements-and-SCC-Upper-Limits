function validate_joint_sensitivity_result(Result, CONF, Stage)
%% 核对阶段输入、诊断、决策变量、成本与安全指标的一致性。

%% 1. 核对输入配置与实际阶段选项
assert(isstruct(Result) && all(isfield(Result, {'CONF', 'Diagnostics'})), ...
    'JointScan:IncompleteResult', '阶段结果缺少必要字段。');
Expected_CONF = apply_multiple_snapshot_solver_stage(CONF, ...
    CONF.Solver.Two_Stage.(sprintf('Stage_%d', Stage)));
Actual_CONF = Result.CONF;
Actual_CONF.solver.options.gurobi.LogFile = '';
Expected_CONF.solver.options.gurobi.LogFile = '';
assert(isequaln(Actual_CONF, Expected_CONF), 'JointScan:ResultInputMismatch', ...
    '已保存的CONF与当前扫描点或阶段输入不一致。');

%% 2. 核对求解诊断；无可行解时保留诊断出口
Diagnostics = Result.Diagnostics;
assert(all(isfield(Diagnostics, {'problem', 'info', 'has_incumbent', 'mip_gap', ...
    'best_bound', 'objective', 'solver_status', 'walltime'})) && ...
    isscalar(Diagnostics.has_incumbent) && isscalar(Diagnostics.problem) && ...
    isscalar(Result.Diagnostics.walltime) && isfinite(Result.Diagnostics.walltime) && Result.Diagnostics.walltime >= 0, ...
    'JointScan:BadDiagnostics', '诊断信息不完整或数值不符合要求。');
assert(~(Diagnostics.has_incumbent && upper(string(Diagnostics.solver_status)) == "INFEASIBLE"), ...
    'JointScan:ContradictoryDiagnostics', '诊断同时报告存在可行解与模型不可行。');
if ~Diagnostics.has_incumbent
    return;
end

%% 3. 核对离散决策变量的维度与取值
assert(all(isfield(Result, {'Cost', 'u_GFM_Unit', 'SecurityValidation', 'SCC_Aggregated', ...
    'SCR_Aggregated', ...
    'SCC_TimeResolved', 'SCR_TimeResolved'})), ...
    'JointScan:IncompleteIncumbent', '可行结果缺少必要字段。');
assert(isequal(size(Result.u_GFM_Unit), ...
    [Expected_CONF.GFM_Candidate_Count, Expected_CONF.GFM_Max_Units_Per_Bus]), ...
    'JointScan:UnitDimensions', '设备投建变量的维度不符合要求。');
Binary_Fields = {'u_GFM_Unit', 'u_G', 'u_G_Start', 'u_G_Stop', 'u_GFM_Ch'};
Binary_Shapes = {[Expected_CONF.GFM_Candidate_Count, Expected_CONF.GFM_Max_Units_Per_Bus], ...
    [Expected_CONF.Gn, Expected_CONF.TypicalDayCount, Expected_CONF.PeriodCount], ...
    [Expected_CONF.Gn, Expected_CONF.TypicalDayCount, Expected_CONF.PeriodCount], ...
    [Expected_CONF.Gn, Expected_CONF.TypicalDayCount, Expected_CONF.PeriodCount], ...
    [Expected_CONF.GFM_Candidate_Count, Expected_CONF.TypicalDayCount, ...
    Expected_CONF.WindScenarioCount, Expected_CONF.PeriodCount]};
for n = 1:numel(Binary_Fields)
    assert(size_matches(Result.(Binary_Fields{n}), Binary_Shapes{n}), ...
        'JointScan:DecisionDimensions', '离散决策变量%s的维度不符合要求。', Binary_Fields{n});
end
for f = Binary_Fields
    Values = Result.(f{1});
    assert(~isempty(Values) && all(isfinite(Values(:))) && ...
        all(abs(Values(:)-round(Values(:))) <= 1e-4) && all(Values(:) >= -1e-4 & Values(:) <= 1+1e-4), ...
        'JointScan:InvalidIntegerSolution', '整数决策变量%s的数值不符合要求。', f{1});
end

%% 4. 核对连续运行变量的维度与有限性
Continuous_Fields = {'P_G', 'P_GFL', 'P_GFL_Curt', 'P_GFM_Dis', 'P_GFM_Ch', 'E_GFM'};
for n = 1:numel(Continuous_Fields)
    if n == 1
        N = Expected_CONF.Gn;
    elseif n <= 3
        N = Expected_CONF.Bn;
    else
        N = Expected_CONF.GFM_Candidate_Count;
    end
    assert(size_matches(Result.(Continuous_Fields{n}), ...
        [N, Expected_CONF.TypicalDayCount, Expected_CONF.WindScenarioCount, Expected_CONF.PeriodCount]), ...
        'JointScan:OperationDimensions', '运行变量%s的维度不符合要求。', Continuous_Fields{n});
end
for f = Continuous_Fields
    Values = Result.(f{1});
    assert(~isempty(Values) && all(isfinite(Values(:))), ...
        'JointScan:InvalidOperation', '运行变量%s为空或包含非有限数值。', f{1});
end

%% 5. 核对成本分项、总成本与求解目标值
Parts = [Result.Cost.GFM_Fixed, Result.Cost.GEN, Result.Cost.UC, Result.Cost.Curt];
Cost_Tolerance = max(1e-4, 1e-8*abs(Result.Cost.Total));
assert(numel(Parts) == 4 && all(isfinite([Parts, Result.Cost.Total])) && ...
    abs(sum(Parts)-Result.Cost.Total) <= Cost_Tolerance && isfinite(Diagnostics.objective) && ...
    abs(Diagnostics.objective-Result.Cost.Total) <= Cost_Tolerance, ...
    'JointScan:CostMismatch', '年成本分项之和、总成本与求解目标值不一致。');

%% 6. 核对聚合与逐时安全指标
assert(size_matches(Result.SCC_Aggregated, [Expected_CONF.Bn, Expected_CONF.TypicalDayCount]) && ...
    size_matches(Result.SCR_Aggregated, [Expected_CONF.Bn, Expected_CONF.TypicalDayCount]) && ...
    size_matches(Result.SCC_TimeResolved, [Expected_CONF.PeriodCount, Expected_CONF.TypicalDayCount, ...
    numel(Expected_CONF.SCC_Constraint_Original_Nodes)]) && ...
    size_matches(Result.SCR_TimeResolved, [Expected_CONF.PeriodCount, Expected_CONF.TypicalDayCount, ...
    numel(Expected_CONF.Safety_GFL_Original_Nodes)]), ...
    'JointScan:SecurityDimensions', '安全指标数组的维度不符合要求。');
Conservatism = check_aggregated_security_conservatism( ...
    Result.SCC_Aggregated, Result.SCR_Aggregated, ...
    Result.SCC_TimeResolved, Result.SCR_TimeResolved, Expected_CONF);
Hourly_Limits = check_converter_security_limits( ...
    Result.SCC_TimeResolved, Result.SCR_TimeResolved, Expected_CONF);
% 聚合状态也须满足本扫描点施加的限值；按单个状态快照交给相同检查函数。
Aggregated_Limits = check_converter_security_limits( ...
    permute(Result.SCC_Aggregated(Expected_CONF.SCC_Constraint_Original_Nodes, :), [3 2 1]), ...
    permute(Result.SCR_Aggregated(Expected_CONF.Safety_GFL_Original_Nodes, :), [3 2 1]), ...
    Expected_CONF);
assert(Conservatism.Passed && Hourly_Limits.Passed && Aggregated_Limits.Passed && ...
    isequaln(Result.SecurityValidation.Conservatism, Conservatism) && ...
    isequaln(Result.SecurityValidation.Limits, Hourly_Limits), ...
    'JointScan:SecurityValidation', '安全指标或已保存的检查记录未通过当前限值与保守性核验。');
end

function Yes = size_matches(Value, Expected)
%% 比较约定维度，允许MATLAB省略末尾长度为1的维度。
Actual = size(Value);
Actual(end+1:numel(Expected)) = 1;
Yes = isequal(Actual, Expected);
end
