function validate_joint_scan_configuration(CONF, Baseline_CONF, I_Limit_kA, SCR_Min)
%% 核对当前扫描限值、系统电流基准与其余固定输入。
assert(CONF.Enable_SCC && CONF.Enable_SCR && ...
    CONF.Consider_Wind_Uncertainty == 1 && CONF.TypicalDayCount == 4 && ...
    CONF.WindScenarioCount == 4 && ...
    all(abs(CONF.I_limit_kA_Node-I_Limit_kA)<1e-12) && ...
    all(abs(CONF.I_limit*CONF.Base_kA-I_Limit_kA)<1e-12) && ...
    abs(CONF.SCR_min-SCR_Min)<1e-12, ...
    'JointScan:ThresholdMismatch', '已加载的安全约束设置与当前扫描点不一致。');
Expected_Base_kA = CONF.Base_MVA/(sqrt(3)*CONF.Base_kV);
assert(abs(CONF.Base_kA-Expected_Base_kA)<1e-12, ...
    'JointScan:CurrentBase', '系统电流基准不一致，单位为kA。');
% 除扫描限值外，UC、储能、场景概率及求解器等输入均须保持一致。
Actual_CONF = CONF;
Expected_CONF = Baseline_CONF;
Actual_CONF = rmfield(Actual_CONF, {'I_limit_kA_Node', 'I_limit', 'SCR_min'});
Expected_CONF = rmfield(Expected_CONF, {'I_limit_kA_Node', 'I_limit', 'SCR_min'});
assert(isequaln(Actual_CONF, Expected_CONF), 'JointScan:NonScanInputChanged', '扫描限值以外的输入发生变化。');
end
