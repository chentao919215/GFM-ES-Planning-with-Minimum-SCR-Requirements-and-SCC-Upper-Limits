function [C_LVRT, C_McCormick] = add_gfl_lvrt_residual_constraints_periodwise( ...
    NET, CONF, u_SG, u_GFM_Module, V_F, V0, Vlin, Vsat, ...
    D0, Dlin, Dsat, Delta_I, Zeta_SG, Zeta_GFM)
%% 构造实际逐时安全状态的三段式LVRT及非故障节点残压约束。
% 对应Manuscript Section II-C，式(13)-(19)与Appendix-B；仅增加(d,t)维，
% 不随风电场景复制。式(18)的交集状态改为实际u_SG(:,d,t)。

CONF = normalize_multiple_snapshot_conf(CONF);
NS = NET.Safety_N;
G = NET.G;
M = CONF.GFM_Module_Count;
D = CONF.TypicalDayCount;
T = CONF.PeriodCount;
GFL_Reduced = NET.Safety_GFL_Reduced_Indices(:);
GFL_Count = numel(GFL_Reduced);
if ~isequal([size(V_F,1),size(V_F,2),size(V_F,3),size(V_F,4)], ...
        [NS,NS,D,T]) || ...
        ~isequal([size(Delta_I,1),size(Delta_I,2), ...
        size(Delta_I,3),size(Delta_I,4)], [NS,GFL_Count,D,T])
    error('PW残余电压或LVRT电流变量维度与安全网络不一致。');
end
if ~isequal([size(Zeta_SG,1),size(Zeta_SG,2),size(Zeta_SG,3), ...
        size(Zeta_SG,4),size(Zeta_SG,5)], [G,NS,NS,D,T]) || ...
        ~isequal([size(Zeta_GFM,1),size(Zeta_GFM,2),size(Zeta_GFM,3), ...
        size(Zeta_GFM,4),size(Zeta_GFM,5)], [M,NS,NS,D,T])
    error('PW残压McCormick辅助变量维度不一致。');
end

% Manuscript式(18)乘以-1后采用非负源电纳幅值，与AG helper同口径。
B0 = -NET.B_0_Safety;
b_SG = -imag(1./(1i*CONF.Xd_Gen(:)));
b_GFM = 1./CONF.GFM_Module_X_Res(:);
Delta_I_Upper = CONF.Delta_I_GFL_pu_Node( ...
    NET.Safety_Retained_Nodes(GFL_Reduced));
Delta_I_Upper_Array = repmat(reshape(Delta_I_Upper,1,GFL_Count,1,1), ...
    NS,1,D,T);
C_LVRT = [V_F(:) >= 0, V_F(:) <= 1, Delta_I(:) >= 0, ...
    Delta_I(:) <= Delta_I_Upper_Array(:)];
C_McCormick = [];

for d = 1:D
    for t = 1:T
        C_LVRT = [C_LVRT, diag(V_F(:,:,d,t)) == 0]; %#ok<AGROW>
        for p = 1:NS
            % Manuscript式(18)：实际SG状态及GFM投建状态与残压的精确乘积。
            U_SG = repmat(u_SG(:,d,t),1,NS);
            X_SG = repmat(V_F(:,p,d,t).',G,1);
            C_McCormick = [C_McCormick, add_binary_product_bounds( ...
                Zeta_SG(:,:,p,d,t),X_SG,U_SG,zeros(G,NS),ones(G,NS))]; %#ok<AGROW>
            U_GFM = repmat(u_GFM_Module,1,NS);
            X_GFM = repmat(V_F(:,p,d,t).',M,1);
            C_McCormick = [C_McCormick, add_binary_product_bounds( ...
                Zeta_GFM(:,:,p,d,t),X_GFM,U_GFM,zeros(M,NS),ones(M,NS))]; %#ok<AGROW>

            Original_Node = NET.Safety_Retained_Nodes(p);
            GFL_Index = find(GFL_Reduced == p,1);
            Module_Index = find(NET.Safety_GFM_Module_Location_Matrix(p,:));
            SG_At_p = b_SG.*full(NET.Safety_Generator_Location_Matrix(p,:)).';
            for n = 1:NS
                if p == n
                    % 故障节点的饱和GFL增量电流由4.4.4的故障节点KCL处理。
                    if ~isempty(GFL_Index)
                        C_LVRT = [C_LVRT, ...
                            D0(n,GFL_Index,d,t) == 0, ...
                            Dlin(n,GFL_Index,d,t) == 0, ...
                            Dsat(n,GFL_Index,d,t) == 0, ...
                            V0(n,GFL_Index,d,t) == 0, ...
                            Vlin(n,GFL_Index,d,t) == 0, ...
                            Vsat(n,GFL_Index,d,t) == 0, ...
                            Delta_I(n,GFL_Index,d,t) == 0]; %#ok<AGROW>
                    end
                    continue;
                end
                if ~isempty(GFL_Index)
                    von = CONF.V_LVRT_On_Node(Original_Node);
                    vsat = CONF.V_LVRT_Sat_Node(Original_Node);
                    Delta_i = Delta_I(n,GFL_Index,d,t);
                    C_LVRT = [C_LVRT, ...
                        D0(n,GFL_Index,d,t)+Dlin(n,GFL_Index,d,t)+ ...
                            Dsat(n,GFL_Index,d,t) == 1, ...
                        von*D0(n,GFL_Index,d,t) <= V0(n,GFL_Index,d,t), ...
                        V0(n,GFL_Index,d,t) <= D0(n,GFL_Index,d,t), ...
                        vsat*Dlin(n,GFL_Index,d,t) <= Vlin(n,GFL_Index,d,t), ...
                        Vlin(n,GFL_Index,d,t) <= von*Dlin(n,GFL_Index,d,t), ...
                        0 <= Vsat(n,GFL_Index,d,t), ...
                        Vsat(n,GFL_Index,d,t) <= vsat*Dsat(n,GFL_Index,d,t), ...
                        Delta_i == CONF.KQ_GFL_Node(Original_Node)* ...
                            CONF.I_GFL_N_pu_Node(Original_Node)* ...
                            (von*Dlin(n,GFL_Index,d,t)-Vlin(n,GFL_Index,d,t)) + ...
                            CONF.Delta_I_GFL_pu_Node(Original_Node)* ...
                            Dsat(n,GFL_Index,d,t), ...
                        V_F(n,p,d,t) == V0(n,GFL_Index,d,t)+ ...
                            Vlin(n,GFL_Index,d,t)+Vsat(n,GFL_Index,d,t)]; %#ok<AGROW>
                    rhs = Delta_i;
                else
                    rhs = 0;
                end
                SG_Term = SG_At_p.'*(Zeta_SG(:,n,p,d,t)-u_SG(:,d,t));
                if isempty(Module_Index)
                    GFM_Term = 0;
                else
                    GFM_Term = b_GFM(Module_Index).'*( ...
                        Zeta_GFM(Module_Index,n,p,d,t)- ...
                        u_GFM_Module(Module_Index));
                end
                lhs = sum(B0(p,[1:n-1,n+1:NS]).* ...
                    V_F(n,[1:n-1,n+1:NS],d,t)) + SG_Term + GFM_Term;
                C_LVRT = [C_LVRT, lhs == rhs]; %#ok<AGROW>
            end
        end
    end
end
end
