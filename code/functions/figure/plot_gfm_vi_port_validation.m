function Figure_Handle = plot_gfm_vi_port_validation(ValidationResult, Figure_File, Style)
%% 从已保存的端口验证结果绘制理论曲线与仿真点，不执行仿真。
Style.Close_After_Save = false;
theory = ValidationResult.Theory;
Points_Table = ValidationResult.Points;
Valid_Mask = Points_Table.Valid;
U_boundary = theory.U_boundary_pu;
I_lim = theory.I_lim_pu;

%% 1. 两状态端口理论曲线与验证散点
% 图窗、坐标范围、网格、曲线及文字风格沿用 plot_gfm_vi_limited.m。
U_PCC_min = 0.00;
U_PCC_max = 1.00;
Num_Points = 501;
Figure_Width_cm = 18.0;
Figure_Height_cm = 5.6;
Label_Font_Size = Style.Label_Size;

U_current_threshold = theory.U_current_threshold_pu;
I_pre_switch = theory.I_pre_switch_pu;
I_post_switch = theory.I_post_switch_pu;
U_PCC_limited = linspace(U_PCC_min, U_boundary, Num_Points);
I_GFM_limited = calculate_gfm_port_current(U_PCC_limited, 1, theory);
U_PCC_unlimited = linspace(U_boundary, U_PCC_max, Num_Points);
I_GFM_unlimited = calculate_gfm_port_current(U_PCC_unlimited, 0, theory);
I_axis_max = 5/3*I_lim;

Font_Name = Style.Font_Name;

figure_handle = new_figure([Figure_Width_cm Figure_Height_cm], Style);
Axes_Handle = axes('Parent', figure_handle);
style_sci_axes(Axes_Handle);
hold(Axes_Handle, 'on');

Curve_Color = Style.Colors.GFM;
Reference_Color = Style.Colors.Reference;

plot(Axes_Handle, U_PCC_unlimited, I_GFM_unlimited, '-', ...
    'Color', Curve_Color, 'LineWidth', 2.2, ...
    'HandleVisibility', 'off');
plot(Axes_Handle, U_PCC_limited, I_GFM_limited, '-', ...
    'Color', Curve_Color, 'LineWidth', 2.2, ...
    'HandleVisibility', 'off');
plot(Axes_Handle, [U_boundary, U_boundary], ...
    [I_post_switch, I_pre_switch], '-', ...
    'Color', Curve_Color, 'LineWidth', 2.2, ...
    'HandleVisibility', 'off');

xlim(Axes_Handle, [U_PCC_min, U_PCC_max]);
ylim(Axes_Handle, [0, I_axis_max]);
xticks(Axes_Handle, linspace(U_PCC_min, U_PCC_max, 5));
yticks(Axes_Handle, 0:0.5:ceil(I_axis_max/0.5)*0.5);

plot(Axes_Handle, [U_PCC_min, U_PCC_max], [I_lim, I_lim], '--', ...
    'Color', Reference_Color, 'LineWidth', 1.5, 'HandleVisibility', 'off');
plot(Axes_Handle, [U_boundary, U_boundary], [0, I_axis_max], '--', ...
    'Color', Reference_Color, 'LineWidth', 1.5, 'HandleVisibility', 'off');
plot(Axes_Handle, U_current_threshold, I_lim, 'o', ...
    'MarkerSize', 7, 'MarkerFaceColor', 'w', ...
    'MarkerEdgeColor', Reference_Color, 'LineWidth', 1.2, ...
    'HandleVisibility', 'off');
plot(Axes_Handle, U_boundary, I_pre_switch, 'o', ...
    'MarkerSize', 7, 'MarkerFaceColor', Reference_Color, ...
    'MarkerEdgeColor', Reference_Color, 'LineWidth', 1.0, ...
    'HandleVisibility', 'off');

Valid_U_PCC = Points_Table.U_PCC_mean_pu(Valid_Mask);
Valid_I_GFM = Points_Table.I_GFM_mean_pu(Valid_Mask);
Scatter_Handle = plot(Axes_Handle, Valid_U_PCC, Valid_I_GFM, 'o', ...
    'LineStyle', 'none', 'MarkerSize', 6.5, ...
    'MarkerFaceColor', Reference_Color, 'MarkerEdgeColor', Reference_Color, ...
    'LineWidth', 0.8, 'DisplayName', 'Simulation');
legend(Axes_Handle, Scatter_Handle, 'Location', 'northwest', ...
    'Box', 'off', 'FontName', Font_Name, 'FontSize', 10);

xlabel(Axes_Handle, '|{\itU}^{PCC}|/{\itU}^N', ...
    'FontName', 'Times New Roman', 'FontSize', Label_Font_Size, ...
    'Color', 'k');
ylabel(Axes_Handle, '|{\itI}^{GFM}|/{\itI}^N', ...
    'FontName', 'Times New Roman', 'FontSize', Label_Font_Size, ...
    'Color', 'k');

text(Axes_Handle, U_boundary+0.43*(U_PCC_max-U_boundary), ...
    0.32*I_lim, {'VI';'off'}, 'Color', Curve_Color, ...
    'FontName', Font_Name, 'FontSize', 12, ...
    'HorizontalAlignment', 'center', 'VerticalAlignment', 'middle');
text(Axes_Handle, U_PCC_min+0.50*(U_boundary-U_PCC_min), ...
    0.28*I_lim, 'Virtual-impedance region', 'Color', [0.25, 0.25, 0.25], ...
    'FontName', Font_Name, 'FontSize', 11, ...
    'HorizontalAlignment', 'center', 'VerticalAlignment', 'middle');
text(Axes_Handle, U_PCC_min+0.50*(U_boundary-U_PCC_min), ...
    0.80*I_lim, 'Slope reduced by virtual impedance', ...
    'Color', Curve_Color, 'FontName', Font_Name, 'FontSize', 10, ...
    'HorizontalAlignment', 'center', 'VerticalAlignment', 'middle');
text(Axes_Handle, 0.3*(U_PCC_max-U_PCC_min), I_lim, ...
    'Current limit \fontname{Times New Roman}{\itI}^{lim}', ...
    'Color', Reference_Color, 'FontName', Font_Name, 'FontSize', 11, ...
    'HorizontalAlignment', 'right', 'VerticalAlignment', 'bottom');
text(Axes_Handle, U_boundary-0.012*(U_PCC_max-U_PCC_min), ...
    0.80*I_axis_max, ...
    'State boundary \fontname{Times New Roman}{\itU}_b', ...
    'Color', Reference_Color, 'FontName', Font_Name, 'FontSize', 11, ...
    'HorizontalAlignment', 'right', 'VerticalAlignment', 'bottom');
text(Axes_Handle, U_current_threshold-0.012*(U_PCC_max-U_PCC_min), ...
    I_lim, 'Current threshold', 'Color', Reference_Color, ...
    'FontName', Font_Name, 'FontSize', 10, ...
    'HorizontalAlignment', 'right', 'VerticalAlignment', 'top');
text(Axes_Handle, U_boundary-0.012*(U_PCC_max-U_PCC_min), ...
    I_pre_switch, 'Switching point', 'Color', Reference_Color, ...
    'FontName', Font_Name, 'FontSize', 10, ...
    'HorizontalAlignment', 'right', 'VerticalAlignment', 'bottom');

Figure_Handle = figure_handle;
if ~isempty(Figure_File)
    save_figure_file(figure_handle, Figure_File);
end
end
