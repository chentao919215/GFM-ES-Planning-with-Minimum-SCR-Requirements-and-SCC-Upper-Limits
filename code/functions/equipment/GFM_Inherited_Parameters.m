function inherited = GFM_Inherited_Parameters(projectRoot)
%GFM_INHERITED_PARAMETERS 集中管理 GFM 模型的外部继承参数。
%
% 本函数只保存/读取来自其它参数源或整定脚本的输入，不负责创建
% Simulink 工作区变量。GFM_Parameters.m 负责把这些输入映射为模型
% 使用的变量，并计算基准换算、派生参数和一致性检查。
%
% 参数来源：
%   1) generate_multiple_snapshot_default_params.m 生成的 JSON：
%      GFM 电气参数以系统基准保存；本函数将其恢复到设备基准。
%   2) GFM_Current_Loop_PI_Calculation.m 和
%      GFM_Voltage_Loop_PI_Calculation.m 的最终整定结果。
%
% 这样，GFM_Parameters.m 中不再重复写入这些外部值，参数来源也可以
% 通过 inherited.Source 追溯。

if nargin < 1 || isempty(projectRoot)
    thisFolder = fileparts(mfilename('fullpath'));
    projectRoot = fileparts(fileparts(fileparts(thisFolder)));
end

if ~isfolder(projectRoot)
    error('GFM project root does not exist: %s', projectRoot);
end

inherited = struct();

%% 1. 来自 GFM 模型及整定脚本的公共物理参数
% 这些值同时被 GFM_Parameters.m 以及控制器整定脚本使用。
inherited.Base = struct( ...
    'V_base', 38.5e3, ...
    'S_base', 60e6, ...
    'V_in', 120e3);

inherited.Filter = struct( ...
    'L1', 1e-3, ...
    'R_L1', 10, ...
    'Cf', 40e-6, ...
    'R_C', 3, ...
    'L2', 600e-6, ...
    'R_L2', 0.05);

inherited.Grid = struct( ...
    'f', 50, ...
    'fs', 10e3, ...
    'i2_lpf_fc', 300, ...
    'SCR', 3, ...
    'MISCR', 3, ...
    'Grid_X_R', 10, ...
    't_close', 0.5);

inherited.Simulation = struct( ...
    't_stop', 6, ...
    'validation_stop_time', 3);

%% 2. 从电流环/电压环整定脚本继承的最终结果
% 这里保留“最终采用值”，而不是在模型初始化时运行带有 clear、绘图
% 和 assignin 的整定脚本。若重新整定了控制器，应在此处更新对应结果，
% 并保留来源脚本中的整定口径。
inherited.CurrentLoop = struct( ...
    'Kp', 5, ...
    'Ki', 1.101049928403827e+04, ...
    'TargetBandwidthHz', 200, ...
    'VoltageFeedforwardMode', 'midpoint_voltage', ...
    'UseDQDecouplingInTuning', false);

inherited.VoltageLoop = struct( ...
    'Kp', 0.013, ...
    'Ki', 0.01, ...
    'TargetBandwidthHz', 50, ...
    'AchievedNominalCrossoverHz', 48.5975701821, ...
    'CurrentToVoltageBandwidthRatio', 4, ...
    'FeedbackVoltage', 'midpoint_voltage', ...
    'InternalVoltageDefinition', 'midpoint_voltage', ...
    'UseI2Feedforward', true, ...
    'UseDQDecouplingInTuning', true, ...
    'NominalPidtuneKp', 0.0128385673255, ...
    'NominalPidtuneKi', 1.2267855989, ...
    'NominalFullLCLMaxPoleReal', 8.69268950509, ...
    'FullLCLMaxPoleReal', -0.100715885869);

%% 3. 下垂控制的外部设计输入
% nq 由目标 Q-E 斜率、L2 和基准阻抗在 GFM_Parameters.m 中派生，
% 避免把残余电抗或滤波器参数重复硬编码到下垂参数表达式中。
inherited.Droop = struct( ...
    'f0', 50, ...
    'theta0', -pi/2, ...
    'E0_pu', 1.0, ...
    'Pref_pu', 0, ...
    'Qref_pu', 0, ...
    'Rf', 0.02, ...
    'Target_nq', 0.1, ...
    'PQ_lpf_fc', 5, ...
    'f_min', 49, ...
    'f_max', 51, ...
    'E_min_pu', 0.85, ...
    'E_max_pu', 1.15, ...
    'StartupLimitDuration', 0.25, ...
    'Startup_f_min', 49.98, ...
    'Startup_f_max', 50.02, ...
    'Startup_E_min_pu', 0.998, ...
    'Startup_E_max_pu', 1.002);

%% 4. 从系统级参数 JSON 继承的 GFM 电气参数
% generate_multiple_snapshot_default_params.m 是可编辑源文件；其 JSON
% 是该源文件生成的运行时接口。这里明确使用 JSON 中的 X_GFM_Res 和
% X_GFM_Vir 进行设备基准恢复，而不是把系统基准数值直接给 Simulink。
jsonFile = fullfile(projectRoot, 'data', 'params', ...
    'multiple_snapshot_default_params.json');
if ~isfile(jsonFile)
    error(['GFM system parameter JSON is missing: %s. ' ...
        'Run generate_multiple_snapshot_default_params.m first.'], jsonFile);
end

systemParams = jsondecode(fileread(jsonFile));
electrical = systemParams.GFM_Modules.Electrical;
module = systemParams.GFM_Modules.Module;
network = systemParams.Network;

iPost = electrical.I_Post_Multiplier(:);
xVirSystem = electrical.X_GFM_Vir(:);
xResSystem = electrical.X_GFM_Res(:);
modulePN = module.PN_MW(:);

if isempty(iPost) || isempty(xVirSystem) || isempty(xResSystem) || ...
        isempty(modulePN)
    error('GFM system electrical parameters are empty.');
end
if any([numel(iPost), numel(xVirSystem), numel(xResSystem), ...
        numel(modulePN)] ~= numel(iPost))
    error('GFM system electrical parameter dimensions are inconsistent.');
end
if any(modulePN <= 0) || network.Base_MVA <= 0
    error('GFM system base values and module ratings must be positive.');
end

% 当前 Simulink 模型表示单个等效设备，因此要求系统级默认参数的各模块
% 采用相同的电流倍数和设备基准残余电抗。
if any(abs(iPost - iPost(1)) > 1e-12) || ...
        any(abs(xVirSystem - xVirSystem(1)) > 1e-12) || ...
        any(abs(xResSystem - xResSystem(1)) > 1e-12) || ...
        any(abs(modulePN - modulePN(1)) > 1e-12)
    error(['The single-device Simulink GFM model requires uniform system-level ' ...
        'GFM electrical parameters across modules.']);
end

systemToDevice = modulePN(1) / network.Base_MVA;
xResDevice = xResSystem(1) * systemToDevice;
xVirDevice = xVirSystem(1) * systemToDevice;
if abs((xResDevice + xVirDevice) - 1/iPost(1)) > 1e-12
    error(['The system-level GFM electrical parameters violate ' ...
        'X_GFM_Res + X_GFM_Vir = 1/I_Post.']);
end

inherited.Electrical = struct( ...
    'I_Post_Multiplier', iPost(1), ...
    'X_GFM_Res_system_pu', xResSystem(1), ...
    'X_GFM_Vir_system_pu', xVirSystem(1), ...
    'X_res_device_pu', xResDevice, ...
    'X_vir_device_pu', xVirDevice, ...
    'Module_PN_MW', modulePN(1), ...
    'Network_Base_MVA', network.Base_MVA);

%% 5. 参数来源登记
inherited.Source = struct( ...
    'SystemParameterSource', fullfile(projectRoot, 'data', 'params', ...
        'generate_multiple_snapshot_default_params.m'), ...
    'SystemParameterRuntimeFile', jsonFile, ...
    'CurrentLoopTuningSource', fullfile(projectRoot, 'code', 'scripts', ...
        'equipment', 'GFM', 'GFM_Current_Loop_PI_Calculation.m'), ...
    'VoltageLoopTuningSource', fullfile(projectRoot, 'code', 'scripts', ...
        'equipment', 'GFM', 'GFM_Voltage_Loop_PI_Calculation.m'));

end
