function inherited = get_gfm_parameter_inputs(Project_Root)
%% 集中管理GFM模型采用的设计输入与系统级电气参数。
%
% 本函数保存原始物理参数和整定设计输入，读取系统级电气参数，
% 不执行整定、不创建Simulink工作区变量。
% initialize_gfm_model.m先派生实际L2，再调用整定函数、检查并发布参数。
%
% 参数来源：
%   1) generate_multiple_snapshot_default_params.m 生成的 JSON：
%      GFM 电气参数以系统基准保存；本函数将其恢复到设备基准。
%   2) 本文件显式列出的目标频率、Kp约束及控制配置。
%
% 参数来源通过inherited.Source追溯；Ki由初始化调用的整定函数计算。

if nargin < 1 || isempty(Project_Root)
    Project_Root = find_project_root(mfilename('fullpath'));
end

if ~isfolder(Project_Root)
    error('GFM project root does not exist: %s', Project_Root);
end

inherited = struct();

%% 1. GFM模型的公共物理参数
% L2不另设标称值，由初始化脚本根据正式残余电抗派生后补入Filter。
inherited.Base = struct( ...
    'V_base', 38.5e3, ...
    'S_base', 60e6, ...
    'V_in', 120e3);

inherited.Filter = struct( ...
    'L1', 1e-3, ...
    'R_L1', 10, ...
    'Cf', 40e-6, ...
    'R_C', 3, ...
    'R_L2', 0.05);

inherited.Grid = struct( ...
    'f', 50, ...
    'fs', 10e3, ...
    'i2_lpf_fc', 300, ...
    'SCR', 3, ...
    'MISCR', 3, ...
    'Grid_X_R', 10, ...
    't_close', 0.5);

inherited.Simulation = struct( ...
    't_stop', 6, ...
    'validation_stop_time', 3);

%% 2. 控制环设计输入（整定函数本身没有默认值）
inherited.CurrentLoopDesign = struct( ...
    'TargetBandwidthHz', 200, 'Kp', 5, 'MinimumPhaseMarginDeg', 35, ...
    'VoltageFeedforwardMode', 'midpoint_voltage', 'UseDQDecouplingInTuning', false, ...
    'ShowRGAPlots', false, 'ShowValidationPlots', false, 'Verbose', false);
% 保留原有Kp，采用已校核的48.6 Hz设计输入；Ki仍须计算并通过实际LCL校核。
% 50 Hz/Kp=0.013的组合不能通过校核，函数不会回退到固定Ki。
inherited.VoltageLoopDesign = struct( ...
    'TargetBandwidthHz', 48.6, 'Kp', 0.013, 'MinimumPhaseMarginDeg', 35, ...
    'UseI2Feedforward', true, 'UseDQDecouplingInTuning', true, ...
    'ShowRGAPlots', false, 'ShowValidationPlots', false, 'Verbose', false);

%% 3. 下垂控制的外部设计输入
% 正式端口验证采用固定内电势口径，nq=0在初始化脚本中明确设置。
% Target_nq保留为设计输入记录，不自动替换当前端口验证采用值。
inherited.Droop = struct( ...
    'f0', 50, ...
    'theta0', -pi/2, ...
    'E0_pu', 1.0, ...
    'Pref_pu', 0, ...
    'Qref_pu', 0, ...
    'Rf', 0.02, ...
    'Target_nq', 0.1, ...
    'PQ_lpf_fc', 5, ...
    'f_min', 49, ...
    'f_max', 51, ...
    'E_min_pu', 0.85, ...
    'E_max_pu', 1.15, ...
    'StartupLimitDuration', 0.25, ...
    'Startup_f_min', 49.98, ...
    'Startup_f_max', 50.02, ...
    'Startup_E_min_pu', 0.998, ...
    'Startup_E_max_pu', 1.002);

%% 4. 从系统级参数 JSON 继承的 GFM 电气参数
% generate_multiple_snapshot_default_params.m 是可编辑源文件；其 JSON
% 是该源文件生成的运行时接口。这里明确使用 JSON 中的 Unit.X_GFM 和
% X_GFM_Vir 进行设备基准恢复，而不是把系统基准数值直接给 Simulink。
JSON_File = fullfile(Project_Root, 'data', 'params', ...
    'multiple_snapshot_default_params.json');
if ~isfile(JSON_File)
    error(['GFM system parameter JSON is missing: %s. ' ...
        'Run generate_multiple_snapshot_default_params.m first.'], JSON_File);
end

System_Params = jsondecode(fileread(JSON_File));
unit = System_Params.GFM_ES.Unit;
network = System_Params.Network;

I_Post = unit.I_Post_Multiplier(:);
X_Vir_System = unit.X_GFM_Vir(:);
X_Res_System = unit.X_GFM(:);
Unit_PN = unit.PN_MW(:);

if isempty(I_Post) || isempty(X_Vir_System) || isempty(X_Res_System) || ...
        isempty(Unit_PN)
    error('GFM system electrical parameters are empty.');
end
if any([numel(I_Post), numel(X_Vir_System), numel(X_Res_System), ...
        numel(Unit_PN)] ~= numel(I_Post))
    error('GFM system electrical parameter dimensions are inconsistent.');
end
if ~isscalar(network.Base_MVA) || ~isfinite(network.Base_MVA) || ...
        network.Base_MVA <= 0 || any(~isfinite([Unit_PN; I_Post; X_Res_System; X_Vir_System])) || ...
        any(Unit_PN <= 0) || any(I_Post <= 0) || ...
        any(X_Res_System <= 0) || any(X_Vir_System <= 0)
    error('GFM system ratings, current limits and reactances must be finite and positive.');
end

% 当前 Simulink 模型表示单个等效设备，因此要求系统级默认参数的各GFM-ES
% 采用相同的电流倍数和设备基准残余电抗。
if any(abs(I_Post - I_Post(1)) > 1e-12) || ...
        any(abs(X_Vir_System - X_Vir_System(1)) > 1e-12) || ...
        any(abs(X_Res_System - X_Res_System(1)) > 1e-12) || ...
        any(abs(Unit_PN - Unit_PN(1)) > 1e-12)
    error(['The single-device Simulink GFM model requires uniform system-level ' ...
        'GFM electrical parameters across units.']);
end

System_To_Device = Unit_PN(1) / network.Base_MVA;
X_Res_Device = X_Res_System(1) * System_To_Device;
X_Vir_Device = X_Vir_System(1) * System_To_Device;
if abs((X_Res_Device + X_Vir_Device) - 1/I_Post(1)) > 1e-12
    error(['The system-level GFM electrical parameters violate ' ...
        'the device-base relation X_GFM + X_GFM_Vir = 1/I_Post_Multiplier.']);
end

inherited.Electrical = struct( ...
    'I_Post_Multiplier', I_Post(1), ...
    'X_GFM_Res_system_pu', X_Res_System(1), ...
    'X_GFM_Vir_system_pu', X_Vir_System(1), ...
    'X_res_device_pu', X_Res_Device, ...
    'X_vir_device_pu', X_Vir_Device, ...
    'Unit_PN_MW', Unit_PN(1), ...
    'Network_Base_MVA', network.Base_MVA);

%% 5. 参数来源登记
inherited.Source = struct( ...
    'SystemParameterSource', fullfile(Project_Root, 'data', 'params', ...
    'generate_multiple_snapshot_default_params.m'), ...
    'SystemParameterRuntimeFile', JSON_File, ...
    'CurrentLoopTuningSource', fullfile(Project_Root, 'code', 'functions', ...
    'equipment', 'tuning', 'tune_gfm_current_loop.m'), ...
    'VoltageLoopTuningSource', fullfile(Project_Root, 'code', 'functions', ...
    'equipment', 'tuning', 'tune_gfm_voltage_loop.m'));
end
