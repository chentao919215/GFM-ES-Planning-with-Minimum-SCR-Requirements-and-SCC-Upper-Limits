function configure_hybrid_report_signals(Model_Name)
%CONFIGURE_HYBRID_REPORT_SIGNALS Add idempotent report signals to the hybrid model.
% The electrical network is not changed.  Only Simulink To Workspace blocks
% are branched from existing measurement/control signals.

if nargin < 1 || isempty(Model_Name)
    Model_Name = bdroot;
end
if ~bdIsLoaded(Model_Name)
    load_system(Model_Name);
end

% Synchronize parameterized source, line, and fault blocks on every run.
% load_system does not replace an already loaded same-named model.
synchronize_hybrid_model_parameters(Model_Name);

% Root-level three-phase terminal measurements.  The measurement blocks are
% already in series with the electrical network; their Simulink outputs are
% unused in the original model, so these branches are non-invasive.
add_to_workspace(Model_Name, ...
    [Model_Name '/Machine Terminal V-I Measurement'], 1, ...
    'Report_Node1_Vabc', [1210 80 1320 110]);
add_to_workspace(Model_Name, ...
    [Model_Name '/Machine Terminal V-I Measurement'], 2, ...
    'Report_Node1_Iabc', [1210 130 1320 160]);
add_to_workspace(Model_Name, ...
    [Model_Name '/Machine Terminal V-I Measurement1'], 1, ...
    'Report_Node2_Vabc', [1210 300 1320 330]);
add_to_workspace(Model_Name, ...
    [Model_Name '/Machine Terminal V-I Measurement1'], 2, ...
    'Report_Node2_Iabc', [1210 350 1320 380]);
add_to_workspace(Model_Name, ...
    [Model_Name '/Fault V-I Measurement'], 1, ...
    'Report_Fault_Vabc', [1210 420 1320 450]);
add_to_workspace(Model_Name, ...
    [Model_Name '/Fault V-I Measurement'], 2, ...
    'Report_Fault_Iabc', [1210 470 1320 500]);

% Node-3 incident branch currents for the short-circuit KCL audit.  The
% branch measurement blocks are inserted in rebuild_hybrid_model.m and do
% not alter z13, z23, or Zth.
add_to_workspace(Model_Name, ...
    [Model_Name '/Line13 V-I Measurement'], 2, ...
    'Report_I13_abc', [1340 420 1450 450]);
add_to_workspace(Model_Name, ...
    [Model_Name '/Line23 V-I Measurement'], 2, ...
    'Report_I23_abc', [1340 470 1450 500]);
add_to_workspace(Model_Name, ...
    [Model_Name '/GridTh V-I Measurement'], 2, ...
    'Report_Ith_abc', [1340 520 1450 550]);

% Record the actual three-phase command applied to the external controlled
% voltage source.  This makes source amplitude/phase mismatches visible in
% the node-3 short-circuit diagnostic.
add_to_workspace(Model_Name, ...
    [Model_Name '/Grid Voltage Command A'], 1, ...
    'Report_Grid_Command_A', [1340 570 1450 600]);
add_to_workspace(Model_Name, ...
    [Model_Name '/Grid Voltage Command B'], 1, ...
    'Report_Grid_Command_B', [1340 620 1450 650]);
add_to_workspace(Model_Name, ...
    [Model_Name '/Grid Voltage Command C'], 1, ...
    'Report_Grid_Command_C', [1340 670 1450 700]);

% GFL dq and LVRT reference signals are already available as ordinary
% subsystem output lines.  These are recorded in the controller's own pu
% base; the report script converts them to system pu where appropriate.
gfl = [Model_Name '/GFL_1'];
add_to_workspace(gfl, [gfl '/PLL与坐标轴变换'], 3, ...
    'Report_GFL_i2_d_pu', [1090 80 1200 110]);
add_to_workspace(gfl, [gfl '/PLL与坐标轴变换'], 4, ...
    'Report_GFL_i2_q_pu', [1090 130 1200 160]);
add_to_workspace(gfl, [gfl '/PLL与坐标轴变换'], 5, ...
    'Report_GFL_vPCC_d_pu', [1090 180 1200 210]);
add_to_workspace(gfl, [gfl '/PLL与坐标轴变换'], 6, ...
    'Report_GFL_vPCC_q_pu', [1090 230 1200 260]);
add_to_workspace(gfl, [gfl '/LVRT与Current_Limit环节'], 1, ...
    'Report_GFL_id_ref_lim_pu', [1090 300 1200 330]);
add_to_workspace(gfl, [gfl '/LVRT与Current_Limit环节'], 2, ...
    'Report_GFL_iq_ref_lim_pu', [1090 350 1200 380]);
end

function synchronize_hybrid_model_parameters(Model_Name)
set_if_present(Model_Name,'z_12',{'BranchType','RL','Resistance','R12_ohm','Inductance','L12_H'});
set_if_present(Model_Name,'z_13',{'BranchType','RL','Resistance','R13_ohm','Inductance','L13_H'});
set_if_present(Model_Name,'z_23',{'BranchType','RL','Resistance','R23_ohm','Inductance','L23_H'});
set_if_present(Model_Name,'Z_th',{'BranchType','RL','Resistance','Rth_ohm','Inductance','Lth_H'});
set_if_present(Model_Name,'Three-Phase Fault',{'SwitchTimes','[t_fault t_clear]', ...
    'FaultResistance','R_fault','GroundResistance','R_fault','Measurements','None'});

for tag = {'A','B','C'}
    suffix = tag{1};
    phase = 'grid_phase_deg';
    Phase_Cmd = 'deg2rad(grid_phase_deg)';
    if suffix == 'B'
        phase = 'grid_phase_deg-120';
        Phase_Cmd = 'deg2rad(grid_phase_deg-120)';
    elseif suffix == 'C'
        phase = 'grid_phase_deg+120';
        Phase_Cmd = 'deg2rad(grid_phase_deg+120)';
    end
    set_if_present(Model_Name,['Grid Controlled Voltage Source ' suffix], ...
        {'Amplitude','E_grid_peak','Phase',phase,'Frequency','f0'});
    set_if_present(Model_Name,['Grid Voltage Command ' suffix], ...
        {'Amplitude','E_grid_peak','Phase',Phase_Cmd,'Frequency','omega0'});
end
end

function set_if_present(Parent_Name, Block_Name, Parameter_Pairs)
Block_Path = [Parent_Name '/' blockName];
if isempty(find_system(parentName,'SearchDepth',1,'Type','Block','Name',Block_Name))
    return;
end
set_param(Block_Path,Parameter_Pairs{:});
end

function add_to_workspace(Parent_Name, Source_Block, Source_Port, Variable_Name, position)
Block_Path = [Parent_Name '/' variableName];
if ~isempty(find_system(parentName,'SearchDepth',1,'Type','Block', ...
        'Name',Variable_Name))
    return;
end
add_block('simulink/Sinks/To Workspace',Block_Path, ...
    'Variable_Name',Variable_Name, ...
    'SaveFormat','Timeseries', ...
    'MaxDataPoints','inf', ...
    'Decimation','1', ...
    'Position',position);
Source_Handles = get_param(Source_Block,'PortHandles');
Target_Handles = get_param(Block_Path,'PortHandles');
add_line(Parent_Name,Source_Handles.Outport(Source_Port),Target_Handles.Inport(1), ...
    'autorouting','smart');
end
