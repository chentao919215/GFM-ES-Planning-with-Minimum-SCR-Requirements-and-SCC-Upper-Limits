%% 典型日内机组组合变化下节点SCR与SCC
clear;
clc;
close all;

%% 1. 数据设置
% 各运行方式的切换时刻
t = [0, 6, 10, 16, 22, 24];

% 阶梯曲线数据
% 最后一个数据用于维持22:00—24:00时段的数值
SCR = [2.40, 2.75, 3.15, 2.80, 2.45, 2.45];
SCC = [9.6, 10.8, 12.6, 11.4, 9.8, 9.8];

% 在线同步机数量
unit_num = [2, 3, 4, 3, 2];

% 约束阈值
SCR_min = 2.5;
SCC_max = 12;

%% 2. 配色设置
blue_color   = [0.00, 0.45, 0.74];   % SCR蓝色
orange_color = [0.85, 0.33, 0.10];   % SCC橙色

gray_color   = [0.35, 0.35, 0.35];
light_gray   = [0.75, 0.75, 0.75];

%% 3. 创建画布
fig = figure( ...
    'Color', 'w', ...
    'Units', 'centimeters', ...
    'Position', [5, 5, 15.5, 8.5]);

ax = axes(fig);
hold(ax, 'on');
box(ax, 'on');

%% 4. 绘制SCR曲线
yyaxis left

hSCR = stairs(t, SCR, ...
    'Color', blue_color, ...
    'LineWidth', 2.4);

ylabel('SCR', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 10, ...
    'FontWeight', 'bold');

ylim([2.2, 3.4]);
yticks(2.2:0.2:3.4);

ax.YAxis(1).Color = blue_color;

% SCR下限
hSCRLimit = yline(SCR_min, '--', ...
    'CSCR=2.5', ...
    'Color', blue_color, ...
    'LineWidth', 1.3, ...
    'LabelHorizontalAlignment', 'left', ...
    'LabelVerticalAlignment', 'top', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 8);

%% 5. 绘制SCC曲线
yyaxis right

hSCC = stairs(t, SCC, ...
    'Color', orange_color, ...
    'LineWidth', 2.4);

ylabel('SCC/kA', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 10, ...
    'FontWeight', 'bold');

ylim([8.5, 13.5]);
yticks(9:1:13);

ax.YAxis(2).Color = orange_color;

% SCC上限
hSCCLimit = yline(SCC_max, '--', ...
    'SCC^{max}=12 kA', ...
    'Color', orange_color, ...
    'LineWidth', 1.3, ...
    'LabelHorizontalAlignment', 'right', ...
    'LabelVerticalAlignment', 'bottom', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 8);

%% 6. 设置横坐标
xlim([0, 24]);
xticks([0, 6, 10, 16, 22, 24]);

xlabel('Times/h', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 10, ...
    'FontWeight', 'bold');

%% 7. 绘制机组启停时刻分界线
switch_time = [6, 10, 16, 22];

for k = 1:length(switch_time)
    xline(switch_time(k), ':', ...
        'Color', light_gray, ...
        'LineWidth', 1.0, ...
        'HandleVisibility', 'off');
end

%% 8. 标注各时段在线机组数量
% 使用右侧纵轴坐标进行标注
yyaxis right

time_mid = (t(1:end-1) + t(2:end)) / 2;
text_y = 13.15;

for k = 1:length(unit_num)
    text(time_mid(k), text_y, ...
        sprintf('%d台机组', unit_num(k)), ...
        'HorizontalAlignment', 'center', ...
        'VerticalAlignment', 'middle', ...
        'FontName', 'Microsoft YaHei', ...
        'FontSize', 8, ...
        'FontWeight', 'bold', ...
        'Color', gray_color);
end

%% 9. 添加关键状态标注
% SCR不足区域
yyaxis left
text(3.0, 2.35, ...
    'SCR<CSCR', ...
    'HorizontalAlignment', 'center', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 8, ...
    'FontWeight', 'bold', ...
    'Color', blue_color);

text(23.0, 2.4, ...
    'SCR<CSCR', ...
    'HorizontalAlignment', 'center', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 8, ...
    'FontWeight', 'bold', ...
    'Color', blue_color);

% SCC超限区域
yyaxis right
text(13.0, 12.8, ...
    'SCC>SCC^{max}', ...
    'HorizontalAlignment', 'center', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 8, ...
    'FontWeight', 'bold', ...
    'Color', orange_color);

%% 10. 图例
legend([hSCR, hSCC], ...
    {'SCR', 'SCC'}, ...
    'Location', 'south', ...
    'Orientation', 'horizontal', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 8, ...
    'Box', 'off');

%% 11. 坐标轴与网格格式
ax.FontName = 'Times New Roman';
ax.FontSize = 8.5;
ax.LineWidth = 1.0;
ax.TickDir = 'out';
ax.XColor = [0.15, 0.15, 0.15];

grid(ax, 'on');
ax.GridLineStyle = ':';
ax.GridAlpha = 0.18;

% 控制图形边距
ax.Position = [0.11, 0.18, 0.78, 0.70];
