function Report = plot_fig8_temporal_model_size(Options)
%% Fig. 8：不同时间尺度下的优化模型规模。
% 读取IV-C归档中的模型规模诊断，仅生成图件。
if nargin < 1
    Options = struct();
end

%% 1. 读取并核验论文算例输入
Script_Directory = fileparts(mfilename('fullpath'));
addpath(fullfile(fileparts(fileparts(fileparts(Script_Directory))), ...
    'functions', 'utils'));
Project_Root = find_project_root(Script_Directory);
Data_Directory = fullfile(Project_Root, 'results_for_case', 'IV-C');
Output_Directory = fullfile(Project_Root, 'figs', 'for_paper');
addpath(genpath(fullfile(Project_Root, 'code', 'functions')));
Options = figure_options(Options, struct('Input_Directory', Data_Directory, 'Output_Directory', ...
    Output_Directory));
Style = figure_style('paper');
Style.Visible = Options.Visible;
Style.Close_After_Save = Options.Close_After_Save;
Data_Directory = Options.Input_Directory;
Output_Directory = Options.Output_Directory;

if ~isfolder(Output_Directory)
    mkdir(Output_Directory);
end

Expected_Period_Counts = [3 6 12 24];
[Fig8_Data, Period_Summary] = load_fig8_data( ...
    Data_Directory, Expected_Period_Counts);

Figure_Width = 3.50;
Figure_Height = 2.40;

%% 2. 绘制论文图件
fig = new_figure(2.54*[Figure_Width Figure_Height], Style);
layout = tiledlayout(fig, 1, 1, 'Padding', 'compact', ...
    'TileSpacing', 'compact');
ax = nexttile(layout);
style_sci_axes(ax);
box(ax, 'off');
hold(ax, 'on');

Aggregated_Color = Style.Colors.Aggregated;
Periodwise_Color = Style.Colors.Periodwise;
Aggregated_Handle = plot(ax, Period_Summary.PeriodCount, ...
    Period_Summary.AggregatedScalarVariableCount_Thousands, '-o', ...
    'Color', Aggregated_Color, ...
    'LineWidth', 0.85, ...
    'MarkerSize', 5.2, ...
    'MarkerFaceColor', Aggregated_Color, ...
    'MarkerEdgeColor', 0.68*Aggregated_Color, ...
    'DisplayName', 'Aggregated');
Periodwise_Handle = plot(ax, Period_Summary.PeriodCount, ...
    Period_Summary.PeriodwiseScalarVariableCount_Thousands, '-s', ...
    'Color', Periodwise_Color, ...
    'LineWidth', 0.85, ...
    'MarkerSize', 5.2, ...
    'MarkerFaceColor', Periodwise_Color, ...
    'MarkerEdgeColor', 0.68*Periodwise_Color, ...
    'DisplayName', 'Period-Wise');
hold(ax, 'off');

xlim(ax, [2 25]);
xticks(ax, Expected_Period_Counts);
ylim(ax, [0 1.10*max(Fig8_Data.ScalarVariableCount_Thousands)]);
set(ax, 'YScale', 'linear');
xlabel(ax, 'Number of periods');
ylabel(ax, 'Scalar decision variables (\times10^3)', ...
    'Interpreter', 'tex');
legend(ax, [Aggregated_Handle Periodwise_Handle], ...
    {'Aggregated', 'Period-Wise'}, ...
    'Location', 'northoutside', ...
    'Orientation', 'horizontal', ...
    'NumColumns', 2, ...
    'FontName', 'Times New Roman', ...
    'FontSize', 7.0, ...
    'Box', 'off');

Output_Base = fullfile(Output_Directory, ...
    'Fig_8_temporal_model_size');
save_figure_file(fig, Output_Base);

fprintf('\nFig. 8 model-size diagnostics by period count:\n');
for Period_Index = 1:height(Period_Summary)
    Summary_Row = Period_Summary(Period_Index, :);
    fprintf(['T=%2d | AG scalar=%d, binary=%d | PW scalar=%d, binary=%d | ', ...
        'PW/AG scalar=%.4f, binary=%.4f\n'], ...
        Summary_Row.PeriodCount, ...
        Summary_Row.AggregatedScalarVariableCount, ...
        Summary_Row.AggregatedBinaryVariableCount, ...
        Summary_Row.PeriodwiseScalarVariableCount, ...
        Summary_Row.PeriodwiseBinaryVariableCount, ...
        Summary_Row.PW_AG_ScalarVariableRatio, ...
        Summary_Row.PW_AG_BinaryVariableRatio);
end
T24_Row = Period_Summary(Period_Summary.PeriodCount == 24, :);
fprintf(['T=24 aggregated relative reduction: scalar=%.6f (%.2f%%), ', ...
    'binary=%.6f (%.2f%%)\n'], ...
    T24_Row.T24_AggregatedScalarReduction, ...
    100*T24_Row.T24_AggregatedScalarReduction, ...
    T24_Row.T24_AggregatedBinaryReduction, ...
    100*T24_Row.T24_AggregatedBinaryReduction);
fprintf('Fig. 8 saved to %s.fig\n', Output_Base);

%% 3. 返回绘图数据与文件位置
Report = struct('Data', Fig8_Data, 'Figure_File', [Output_Base '.fig']);
Report.Summary = Period_Summary;
end

function [Fig8_Data, Period_Summary] = load_fig8_data( ...
    Data_Directory, Expected_Period_Counts)
%% 按时间尺度与AG/PW组合读取阶段归档，并核验元数据。

if ~isfolder(Data_Directory)
    error('Fig8:MissingDataDirectory', ...
        'IV-C data directory does not exist: %s', Data_Directory);
end

% IV-C归档以_1、_2后缀区分实际求解阶段。
Formulation_Keys = ["AG", "PW"];
Formulation_Labels = ["Aggregated", "Period-Wise"];
Row_Count = numel(Expected_Period_Counts)*numel(Formulation_Keys);
Period_Column = zeros(Row_Count, 1);
Formulation_Column = strings(Row_Count, 1);
Scalar_Count_Column = zeros(Row_Count, 1);
Binary_Count_Column = zeros(Row_Count, 1);
Result_File_Column = strings(Row_Count, 1);
Stage2_Result_File_Column = strings(Row_Count, 1);
Row_Index = 0;

for Period_Index = 1:numel(Expected_Period_Counts)
    Expected_Period_Count = Expected_Period_Counts(Period_Index);
    for Formulation_Index = 1:numel(Formulation_Keys)
        Formulation_Key = Formulation_Keys(Formulation_Index);
        if Formulation_Key == "AG"
            Expected_Formulation = "aggregated";
        else
            Expected_Formulation = "periodwise";
        end
        File_Name = sprintf('T%02d_%s_1.mat', ...
            Expected_Period_Count, Formulation_Key);
        File_Path = fullfile(Data_Directory, File_Name);
        if ~isfile(File_Path)
            error('Fig8:MissingResultFile', ...
                'Required IV-C result file is missing: %s', File_Path);
        end

        Loaded = load(File_Path, 'Result');
        if ~isfield(Loaded, 'Result') || ~isstruct(Loaded.Result)
            error('Fig8:MissingResult', ...
                'MAT file does not contain a Result structure: %s', File_Path);
        end
        Result = Loaded.Result;
        if ~isfield(Result, 'CONF') || ~isstruct(Result.CONF) || ...
                ~isfield(Result.CONF, 'PeriodCount')
            error('Fig8:MissingPeriodCount', ...
                'Result.CONF.PeriodCount is missing: %s', File_Path);
        end
        Actual_Period_Count = Result.CONF.PeriodCount;
        if ~isnumeric(Actual_Period_Count) || ...
                ~isreal(Actual_Period_Count) || ...
                ~isscalar(Actual_Period_Count) || ...
                ~isfinite(Actual_Period_Count) || ...
                Actual_Period_Count ~= round(Actual_Period_Count) || ...
                Actual_Period_Count ~= Expected_Period_Count
            error('Fig8:PeriodCountMismatch', ...
                ['Expected T=%d from %s, but Result.CONF.PeriodCount ', ...
                'is missing, invalid, or inconsistent.'], ...
                Expected_Period_Count, File_Path);
        end

        if ~isfield(Result.CONF, 'SecurityFormulation') || ...
                ~(ischar(Result.CONF.SecurityFormulation) || ...
                (isstring(Result.CONF.SecurityFormulation) && ...
                isscalar(Result.CONF.SecurityFormulation)))
            error('Fig8:MissingFormulation', ...
                'Result.CONF.SecurityFormulation is missing or invalid: %s', ...
                File_Path);
        end
        Actual_Formulation = lower(string(Result.CONF.SecurityFormulation));
        if Actual_Formulation ~= Expected_Formulation
            error('Fig8:FormulationMismatch', ...
                ['Expected %s formulation from %s, but the saved result ', ...
                'identifies itself as %s.'], ...
                Expected_Formulation, File_Path, Actual_Formulation);
        end

        if ~isfield(Result, 'Diagnostics') || ...
                ~isstruct(Result.Diagnostics)
            error('Fig8:MissingDiagnostics', ...
                'Result.Diagnostics is missing or invalid: %s', File_Path);
        end
        Required_Count_Fields = { ...
            'Scalar_Variable_Count', 'Binary_Variable_Count'};
        Missing_Count_Fields = Required_Count_Fields( ...
            ~isfield(Result.Diagnostics, Required_Count_Fields));
        if ~isempty(Missing_Count_Fields)
            error('Fig8:MissingVariableCounts', ...
                'Result.Diagnostics in %s is missing: %s.', ...
                File_Path, strjoin(Missing_Count_Fields, ', '));
        end

        Scalar_Count = Result.Diagnostics.Scalar_Variable_Count;
        Binary_Count = Result.Diagnostics.Binary_Variable_Count;
        validate_positive_integer_count(Scalar_Count, ...
            'Scalar_Variable_Count', File_Path);
        validate_positive_integer_count(Binary_Count, ...
            'Binary_Variable_Count', File_Path);

        % 若执行了第二阶段，核验其模型规模诊断与第一阶段一致。
        Stage2_File_Path = fullfile(Data_Directory, sprintf( ...
            'T%02d_%s_2.mat', Expected_Period_Count, Formulation_Key));
        if isfile(Stage2_File_Path)
            Loaded_Stage2 = load(Stage2_File_Path, 'Result');
            if ~isfield(Loaded_Stage2, 'Result') || ...
                    ~isstruct(Loaded_Stage2.Result)
                error('Fig8:MissingStage2Result', ...
                    'Stage-2 MAT file has no Result structure: %s', ...
                    Stage2_File_Path);
            end
            Stage2_Result = Loaded_Stage2.Result;
            if ~isfield(Stage2_Result, 'CONF') || ...
                    ~isstruct(Stage2_Result.CONF) || ...
                    ~isfield(Stage2_Result.CONF, 'PeriodCount') || ...
                    Stage2_Result.CONF.PeriodCount ~= Expected_Period_Count || ...
                    ~isfield(Stage2_Result.CONF, 'SecurityFormulation') || ...
                    lower(string(Stage2_Result.CONF.SecurityFormulation)) ~= ...
                    Expected_Formulation
                error('Fig8:Stage2IdentityMismatch', ...
                    'Stage-2 result does not match T/formulation: %s', ...
                    Stage2_File_Path);
            end
            if ~isfield(Stage2_Result, 'Diagnostics') || ...
                    ~isstruct(Stage2_Result.Diagnostics) || ...
                    ~all(isfield(Stage2_Result.Diagnostics, ...
                    Required_Count_Fields))
                error('Fig8:MissingStage2VariableCounts', ...
                    'Stage-2 variable-count diagnostics are missing: %s', ...
                    Stage2_File_Path);
            end
            Stage2_Scalar_Count = ...
                Stage2_Result.Diagnostics.Scalar_Variable_Count;
            Stage2_Binary_Count = ...
                Stage2_Result.Diagnostics.Binary_Variable_Count;
            validate_positive_integer_count(Stage2_Scalar_Count, ...
                'Scalar_Variable_Count', Stage2_File_Path);
            validate_positive_integer_count(Stage2_Binary_Count, ...
                'Binary_Variable_Count', Stage2_File_Path);
            if Stage2_Scalar_Count ~= Scalar_Count || ...
                    Stage2_Binary_Count ~= Binary_Count
                error('Fig8:StageModelSizeMismatch', ...
                    ['Stage-1 and Stage-2 variable counts disagree ', ...
                    'for %s.'], File_Name);
            end
            Stage2_Result_File_Column(Row_Index + 1) = ...
                string(Stage2_File_Path);
        end

        Row_Index = Row_Index + 1;
        Period_Column(Row_Index) = Expected_Period_Count;
        Formulation_Column(Row_Index) = Formulation_Labels(Formulation_Index);
        Scalar_Count_Column(Row_Index) = double(Scalar_Count);
        Binary_Count_Column(Row_Index) = double(Binary_Count);
        Result_File_Column(Row_Index) = string(File_Path);
    end
end

if Row_Index ~= Row_Count
    error('Fig8:IncompleteData', ...
        'Expected %d validated results, but read %d.', Row_Count, Row_Index);
end

Fig8_Data = table(Period_Column, Formulation_Column, ...
    Scalar_Count_Column, Scalar_Count_Column/1e3, ...
    Binary_Count_Column, Result_File_Column, Stage2_Result_File_Column, ...
    'VariableNames', {'PeriodCount', 'Formulation', ...
    'ScalarVariableCount', 'ScalarVariableCount_Thousands', ...
    'BinaryVariableCount', 'ResultFile', 'Stage2ResultFile'});

Periodwise_Scalar = zeros(numel(Expected_Period_Counts), 1);
Aggregated_Scalar = zeros(numel(Expected_Period_Counts), 1);
Periodwise_Binary = zeros(numel(Expected_Period_Counts), 1);
Aggregated_Binary = zeros(numel(Expected_Period_Counts), 1);
Scalar_Ratio = zeros(numel(Expected_Period_Counts), 1);
Binary_Ratio = zeros(numel(Expected_Period_Counts), 1);
for Period_Index = 1:numel(Expected_Period_Counts)
    Period_Count = Expected_Period_Counts(Period_Index);
    Is_Period = Fig8_Data.PeriodCount == Period_Count;
    Is_Aggregated = Is_Period & Fig8_Data.Formulation == "Aggregated";
    Is_Periodwise = Is_Period & Fig8_Data.Formulation == "Period-Wise";
    if nnz(Is_Aggregated) ~= 1 || nnz(Is_Periodwise) ~= 1
        error('Fig8:IncompleteFormulationPair', ...
            'Expected exactly one AG and one PW result at T=%d.', Period_Count);
    end
    Aggregated_Scalar(Period_Index) = ...
        Fig8_Data.ScalarVariableCount(Is_Aggregated);
    Periodwise_Scalar(Period_Index) = ...
        Fig8_Data.ScalarVariableCount(Is_Periodwise);
    Aggregated_Binary(Period_Index) = ...
        Fig8_Data.BinaryVariableCount(Is_Aggregated);
    Periodwise_Binary(Period_Index) = ...
        Fig8_Data.BinaryVariableCount(Is_Periodwise);
    Scalar_Ratio(Period_Index) = ...
        Periodwise_Scalar(Period_Index)/Aggregated_Scalar(Period_Index);
    Binary_Ratio(Period_Index) = ...
        Periodwise_Binary(Period_Index)/Aggregated_Binary(Period_Index);
end

T24_Index = find(Expected_Period_Counts == 24, 1);
if isempty(T24_Index)
    error('Fig8:MissingT24', ...
        'T=24 is required to calculate the relative reductions.');
end
T24_Scalar_Reduction = 1 - ...
    Aggregated_Scalar(T24_Index)/Periodwise_Scalar(T24_Index);
T24_Binary_Reduction = 1 - ...
    Aggregated_Binary(T24_Index)/Periodwise_Binary(T24_Index);

Fig8_Data.PW_AG_ScalarVariableRatio = ...
    nan(height(Fig8_Data), 1);
Fig8_Data.PW_AG_BinaryVariableRatio = ...
    nan(height(Fig8_Data), 1);
Fig8_Data.T24_AggregatedScalarReduction = ...
    nan(height(Fig8_Data), 1);
Fig8_Data.T24_AggregatedScalarReductionPercent = ...
    nan(height(Fig8_Data), 1);
Fig8_Data.T24_AggregatedBinaryReduction = ...
    nan(height(Fig8_Data), 1);
Fig8_Data.T24_AggregatedBinaryReductionPercent = ...
    nan(height(Fig8_Data), 1);
for Period_Index = 1:numel(Expected_Period_Counts)
    Is_Period = Fig8_Data.PeriodCount == ...
        Expected_Period_Counts(Period_Index);
    Fig8_Data.PW_AG_ScalarVariableRatio(Is_Period) = ...
        Scalar_Ratio(Period_Index);
    Fig8_Data.PW_AG_BinaryVariableRatio(Is_Period) = ...
        Binary_Ratio(Period_Index);
end
Is_T24 = Fig8_Data.PeriodCount == 24;
Fig8_Data.T24_AggregatedScalarReduction(Is_T24) = T24_Scalar_Reduction;
Fig8_Data.T24_AggregatedScalarReductionPercent(Is_T24) = ...
    100*T24_Scalar_Reduction;
Fig8_Data.T24_AggregatedBinaryReduction(Is_T24) = T24_Binary_Reduction;
Fig8_Data.T24_AggregatedBinaryReductionPercent(Is_T24) = ...
    100*T24_Binary_Reduction;

Period_Summary = table(Expected_Period_Counts(:), ...
    Aggregated_Scalar, Periodwise_Scalar, ...
    Aggregated_Scalar/1e3, Periodwise_Scalar/1e3, ...
    Aggregated_Binary, Periodwise_Binary, Scalar_Ratio, Binary_Ratio, ...
    nan(numel(Expected_Period_Counts), 1), ...
    nan(numel(Expected_Period_Counts), 1), ...
    'VariableNames', {'PeriodCount', ...
    'AggregatedScalarVariableCount', 'PeriodwiseScalarVariableCount', ...
    'AggregatedScalarVariableCount_Thousands', ...
    'PeriodwiseScalarVariableCount_Thousands', ...
    'AggregatedBinaryVariableCount', 'PeriodwiseBinaryVariableCount', ...
    'PW_AG_ScalarVariableRatio', 'PW_AG_BinaryVariableRatio', ...
    'T24_AggregatedScalarReduction', 'T24_AggregatedBinaryReduction'});
Period_Summary.T24_AggregatedScalarReduction(T24_Index) = ...
    T24_Scalar_Reduction;
Period_Summary.T24_AggregatedBinaryReduction(T24_Index) = ...
    T24_Binary_Reduction;
end

function validate_positive_integer_count(Value, Field_Name, File_Path)
%% 核验模型规模计数为有限正整数。
if ~isnumeric(Value) || ~isreal(Value) || ~isscalar(Value) || ...
        ~isfinite(Value) || Value <= 0 || Value ~= round(Value)
    error('Fig8:InvalidVariableCount', ...
        'Result.Diagnostics.%s must be a finite positive integer: %s', ...
        Field_Name, File_Path);
end
end
