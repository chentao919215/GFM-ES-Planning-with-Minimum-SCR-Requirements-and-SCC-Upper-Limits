function Report = plot_fig9_temporal_solution_time(Options)
%% Fig. 9：日内时段数与求解器时间的关系。
% 仅从阶段归档读取结果，不启动规划求解。
% 缺少第二阶段时，以删失点标记已知求解时间下界。
% 第一阶段缺失、阶段含义不明确或时间无效时直接报错。
if nargin < 1
    Options = struct();
end

%% 1. 读取并核验论文算例输入
Script_Directory = fileparts(mfilename('fullpath'));
addpath(fullfile(fileparts(fileparts(fileparts(Script_Directory))), ...
    'functions', 'utils'));
Project_Root = find_project_root(Script_Directory);
Data_Directory = fullfile(Project_Root, 'results_for_case', 'IV-C');
Output_Directory = fullfile(Project_Root, 'figs', 'for_paper');
addpath(genpath(fullfile(Project_Root, 'code', 'functions')));
Options = figure_options(Options, struct('Input_Directory', Data_Directory, 'Output_Directory', ...
    Output_Directory));
Style = figure_style('paper');
Style.Visible = Options.Visible;
Style.Close_After_Save = Options.Close_After_Save;
Data_Directory = Options.Input_Directory;
Output_Directory = Options.Output_Directory;

if ~isfolder(Output_Directory)
    mkdir(Output_Directory);
end

Expected_Period_Counts = [3 6 12 24];
[Fig9_Data, Period_Summary] = load_fig9_data( ...
    Data_Directory, Expected_Period_Counts);
print_fig9_diagnostics(Period_Summary);

Figure_Width = 3.50;
Figure_Height = 2.40;

%% 2. 绘制论文图件
fig = new_figure(2.54*[Figure_Width Figure_Height], Style);
layout = tiledlayout(fig, 1, 1, 'Padding', 'compact', ...
    'TileSpacing', 'compact');
ax = nexttile(layout);
style_sci_axes(ax);
box(ax, 'off');
hold(ax, 'on');

Aggregated_Color = Style.Colors.Aggregated;
Periodwise_Color = Style.Colors.Periodwise;
Formulations = ["Aggregated", "Period-wise"];
Formulation_Colors = {Aggregated_Color, Periodwise_Color};
Formulation_Markers = {'o', 's'};
Legend_Handles = gobjects(2, 1);

for Formulation_Index = 1:2
    Formulation = Formulations(Formulation_Index);
    Is_Formulation = Fig9_Data.Formulation == Formulation;
    Is_Target_Met = Is_Formulation & Fig9_Data.ReachedTarget;
    Is_Censored = Is_Formulation & Fig9_Data.Censored;
    Color = Formulation_Colors{Formulation_Index};
    Marker = Formulation_Markers{Formulation_Index};

    Target_Data = Fig9_Data(Is_Target_Met, :);
    Target_Data = sortrows(Target_Data, 'PeriodCount');
    if isempty(Target_Data)
        error('Fig9:MissingTargetMetSeries', ...
            'No target-met point is available for %s.', Formulation);
    end
    Legend_Handles(Formulation_Index) = plot(ax, ...
        Target_Data.PeriodCount, Target_Data.TotalSolveTime_s, ...
        ['-' Marker], ...
        'Color', Color, ...
        'LineWidth', 0.85, ...
        'MarkerSize', 5.2, ...
        'MarkerFaceColor', Color, ...
        'MarkerEdgeColor', 0.68*Color, ...
        'DisplayName', char(Formulation));

    Censored_Data = Fig9_Data(Is_Censored, :);
    % 将删失点连接到相邻的前一时间尺度结果，与前一点是否达到目标无关。
    for Point_Index = 1:height(Censored_Data)
        Period_Count = Censored_Data.PeriodCount(Point_Index);
        Previous_Data = Fig9_Data( ...
            Is_Formulation & Fig9_Data.PeriodCount < Period_Count, :);
        Previous_Data = sortrows(Previous_Data, 'PeriodCount');
        if ~isempty(Previous_Data)
            Previous_Point = Previous_Data(end, :);
            plot(ax, ...
                [Previous_Point.PeriodCount Period_Count], ...
                [Previous_Point.TotalSolveTime_s ...
                Censored_Data.TotalSolveTime_s(Point_Index)], ...
                '--', ...
                'Color', Color, ...
                'LineWidth', 0.85, ...
                'HandleVisibility', 'off');
        end
    end
    for Point_Index = 1:height(Censored_Data)
        Period_Count = Censored_Data.PeriodCount(Point_Index);
        Time_Spent = Censored_Data.TotalSolveTime_s(Point_Index);
        plot(ax, Period_Count, Time_Spent, Marker, ...
            'LineStyle', 'none', ...
            'MarkerSize', 5.2, ...
            'MarkerFaceColor', 'w', ...
            'MarkerEdgeColor', Color, ...
            'LineWidth', 0.9, ...
            'HandleVisibility', 'off');
        text(ax, Period_Count-0.30, 1.48*Time_Spent, ...
            sprintf('gap = %.1f%%', ...
            100*Censored_Data.FinalMIPGap(Point_Index)), ...
            'FontName', 'Times New Roman', ...
            'FontSize', 6.7, ...
            'Color', Color, ...
            'HorizontalAlignment', 'right', ...
            'VerticalAlignment', 'bottom', ...
            'HandleVisibility', 'off');
    end
end
hold(ax, 'off');

All_Times = Fig9_Data.TotalSolveTime_s;
if any(~isfinite(All_Times) | All_Times <= 0)
    error('Fig9:InvalidPlotTime', ...
        'Every final solution time must be finite and positive.');
end
Lower_Y = min(All_Times)/1.8;
Upper_Y = max(All_Times)*1.8;
if any(Fig9_Data.Censored)
    Upper_Y = max(Upper_Y, ...
        2.2*max(Fig9_Data.TotalSolveTime_s(Fig9_Data.Censored)));
end
ylim(ax, [Lower_Y Upper_Y]);
xlim(ax, [2 25]);
xticks(ax, Expected_Period_Counts);
set(ax, 'YScale', 'log');
yticks(ax, [10 100 1000]);
xlabel(ax, 'Number of periods');
ylabel(ax, 'Total solver time (s)');
legend(ax, Legend_Handles, {'Aggregated', 'Period-Wise'}, ...
    'Location', 'northoutside', ...
    'Orientation', 'horizontal', ...
    'NumColumns', 2, ...
    'FontName', 'Times New Roman', ...
    'FontSize', 7.0, ...
    'Box', 'off');

Output_Base = fullfile(Output_Directory, ...
    'Fig_9_temporal_solution_time');
save_figure_file(fig, Output_Base);
fprintf('Fig. 9 saved to %s.fig\n', Output_Base);

%% 3. 返回绘图数据与文件位置
Report = struct('Data', Fig9_Data, 'Figure_File', [Output_Base '.fig']);
Report.Summary = Period_Summary;
end

function [Fig9_Data, Period_Summary] = load_fig9_data( ...
    Data_Directory, Expected_Period_Counts)
%% 读取带阶段后缀的MAT归档，并核验最终求解设置。

if ~isfolder(Data_Directory)
    error('Fig9:FinalizedResultsRequired', ...
        ['Finalized IV-C results are required for Fig. 9. ', ...
        'Data directory is missing: %s'], Data_Directory);
end

Formulation_Keys = ["AG", "PW"];
Formulation_Labels = ["Aggregated", "Period-wise"];
Point_Count = numel(Expected_Period_Counts)*numel(Formulation_Keys);
Stage1_Results = cell(Point_Count, 1);
Stage2_Results = cell(Point_Count, 1);
Stage1_Paths = strings(Point_Count, 1);
Stage2_Paths = strings(Point_Count, 1);
Period_Column = zeros(Point_Count, 1);
Formulation_Column = strings(Point_Count, 1);
Write_Index = 0;
Target_Gap_Candidates = [];
Issues = strings(0, 1);

for Period_Index = 1:numel(Expected_Period_Counts)
    Period_Count = Expected_Period_Counts(Period_Index);
    for Formulation_Index = 1:numel(Formulation_Keys)
        Write_Index = Write_Index + 1;
        Formulation_Key = Formulation_Keys(Formulation_Index);
        Formulation = Formulation_Labels(Formulation_Index);
        Expected_Metadata_Formulation = ...
            expected_formulation_value(Formulation_Key);
        Stage1_Path = fullfile(Data_Directory, sprintf( ...
            'T%02d_%s_1.mat', Period_Count, Formulation_Key));
        Stage2_Path = fullfile(Data_Directory, sprintf( ...
            'T%02d_%s_2.mat', Period_Count, Formulation_Key));

        Period_Column(Write_Index) = Period_Count;
        Formulation_Column(Write_Index) = Formulation;
        Stage1_Paths(Write_Index) = string(Stage1_Path);
        if ~isfile(Stage1_Path)
            Issues(end+1, 1) = sprintf( ...
                'Missing Stage-1 result: %s', Stage1_Path);
            continue;
        end

        try
            Stage1_Results{Write_Index} = read_stage_result( ...
                Stage1_Path, Period_Count, Expected_Metadata_Formulation, ...
                "feasible-search");
        catch ME
            Issues(end+1, 1) = string(ME.message);
            % 即使首个文件的阶段元数据无效，也保留重复文件的诊断信息。
            if isfile(Stage2_Path)
                try
                    Raw_Stage1 = load(Stage1_Path, 'Result');
                    Raw_Stage2 = load(Stage2_Path, 'Result');
                    if isfield(Raw_Stage1, 'Result') && ...
                            isfield(Raw_Stage2, 'Result') && ...
                            isequaln(Raw_Stage1.Result, Raw_Stage2.Result)
                        Issues(end+1, 1) = sprintf( ...
                            ['Stage-2 file exactly duplicates the ', ...
                            'unaccepted Stage-1 file: %s'], Stage2_Path);
                    end
                catch
                    % 保留首次阶段核验错误即可定位问题。
                end
            end
        end

        if isfile(Stage2_Path)
            Stage2_Paths(Write_Index) = string(Stage2_Path);
            try
                Stage2_Results{Write_Index} = read_stage_result( ...
                    Stage2_Path, Period_Count, Expected_Metadata_Formulation, ...
                    "optimality-proof");
                Target_Gap_Candidates(end+1, 1) = ...
                    Stage2_Results{Write_Index}.ConfiguredMIPGap;
            catch ME
                Issues(end+1, 1) = string(ME.message);
            end
        end
    end
end

if isempty(Target_Gap_Candidates)
    Issues(end+1, 1) = ...
        "No Stage-2 solver configuration supplies the target MIP gap.";
    Target_MIP_Gap = NaN;
else
    Target_MIP_Gap = Target_Gap_Candidates(1);
    if any(abs(Target_Gap_Candidates-Target_MIP_Gap) > 1e-12)
        Issues(end+1, 1) = ...
            "Stage-2 target MIP-gap settings are inconsistent across results.";
    end
end

Stage1_Time = nan(Point_Count, 1);
Stage2_Time = zeros(Point_Count, 1);
Total_Time = nan(Point_Count, 1);
Final_Gap = nan(Point_Count, 1);
Stage1_Limit = nan(Point_Count, 1);
Stage2_Limit = nan(Point_Count, 1);
Has_Incumbent = false(Point_Count, 1);
Reached_Target = false(Point_Count, 1);
Censored = false(Point_Count, 1);
Solver_Backend = strings(Point_Count, 1);
Solver_Problem = nan(Point_Count, 1);
Solver_Info = strings(Point_Count, 1);
Status = strings(Point_Count, 1);
Result_File = strings(Point_Count, 1);

for Point_Index = 1:Point_Count
    Stage1 = Stage1_Results{Point_Index};
    Stage2 = Stage2_Results{Point_Index};
    if isempty(Stage1)
        continue;
    end
    Stage1_Time(Point_Index) = Stage1.SolverTime_s;
    Stage1_Limit(Point_Index) = Stage1.TimeLimit_s;

    if ~isfinite(Target_MIP_Gap)
        continue;
    end
    if ~isempty(Stage2)
        if isequaln(Stage1.Result, Stage2.Result)
            Issues(end+1, 1) = sprintf( ...
                ['Stage-2 file is an exact duplicate of Stage 1; ', ...
                'it does not establish a finalized second phase: %s'], ...
                Stage2.FilePath);
            continue;
        end
        if Stage1.MIPGap <= Target_MIP_Gap + 1e-12
            Issues(end+1, 1) = sprintf( ...
                ['A Stage-2 result exists although Stage 1 already met ', ...
                'the target for T=%d, %s; the archived pair is ambiguous.'], ...
                Period_Column(Point_Index), Formulation_Column(Point_Index));
            continue;
        end
        Stage2_Time(Point_Index) = Stage2.SolverTime_s;
        Stage2_Limit(Point_Index) = Stage2.TimeLimit_s;
        Final_Stage = Stage2;
        Result_File(Point_Index) = string(Stage2.FilePath);
    else
        Final_Stage = Stage1;
        Result_File(Point_Index) = string(Stage1.FilePath);
    end

    Total_Time(Point_Index) = ...
        Stage1_Time(Point_Index) + Stage2_Time(Point_Index);
    Final_Gap(Point_Index) = Final_Stage.MIPGap;
    Has_Incumbent(Point_Index) = Final_Stage.HasIncumbent;
    Reached_Target(Point_Index) = ...
        Final_Gap(Point_Index) <= Target_MIP_Gap + 1e-12;
    Censored(Point_Index) = ...
        Has_Incumbent(Point_Index) && ~Reached_Target(Point_Index);
    Solver_Backend(Point_Index) = string(Final_Stage.SolverBackend);
    Solver_Problem(Point_Index) = Final_Stage.Problem;
    Solver_Info(Point_Index) = string(Final_Stage.Info);
    if Reached_Target(Point_Index)
        Status(Point_Index) = "target_met";
    elseif isempty(Stage2)
        Status(Point_Index) = "stage2_missing";
    else
        Status(Point_Index) = "feasible_target_not_met";
    end
end

if ~isempty(Issues)
    error('Fig9:FinalizedResultsRequired', ...
        ['Finalized IV-C results are required for Fig. 9. ', ...
        'No final figure or CSV was written. Details: %s'], ...
        strjoin(Issues, ' | '));
end

Fig9_Data = table(Period_Column, Formulation_Column, ...
    Stage1_Time, Stage2_Time, Total_Time, Final_Gap, ...
    repmat(Target_MIP_Gap, Point_Count, 1), Has_Incumbent, ...
    Reached_Target, Censored, Stage1_Limit, Stage2_Limit, ...
    Status, Solver_Backend, Solver_Problem, Solver_Info, ...
    Stage1_Paths, Stage2_Paths, Result_File, ...
    'VariableNames', {'PeriodCount', 'Formulation', ...
    'Stage1SolveTime_s', 'Stage2SolveTime_s', 'TotalSolveTime_s', ...
    'FinalMIPGap', 'TargetMIPGap', 'HasIncumbent', 'ReachedTarget', ...
    'Censored', 'Stage1TimeLimit_s', 'Stage2TimeLimit_s', 'Status', ...
    'SolverBackend', 'SolverProblem', 'SolverInfo', 'Stage1ResultFile', ...
    'Stage2ResultFile', 'ResultFile'});

% 两种安全表示须采用相同目标间隙，求解时间必须为正。
Period_Summary = table(Expected_Period_Counts(:), ...
    nan(numel(Expected_Period_Counts), 1), ...
    nan(numel(Expected_Period_Counts), 1), ...
    nan(numel(Expected_Period_Counts), 1), ...
    nan(numel(Expected_Period_Counts), 1), ...
    nan(numel(Expected_Period_Counts), 1), ...
    nan(numel(Expected_Period_Counts), 1), ...
    nan(numel(Expected_Period_Counts), 1), ...
    nan(numel(Expected_Period_Counts), 1), ...
    nan(numel(Expected_Period_Counts), 1), ...
    nan(numel(Expected_Period_Counts), 1), ...
    'VariableNames', {'PeriodCount', 'AggregatedSolveTime_s', ...
    'PeriodwiseSolveTime_s', 'AggregatedFinalMIPGap', ...
    'PeriodwiseFinalMIPGap', 'PW_AG_SolutionTimeRatio', ...
    'PW_AG_TargetTimeRatioLowerBound', ...
    'AggregatedStage1TimeLimit_s', 'AggregatedStage2TimeLimit_s', ...
    'PeriodwiseStage1TimeLimit_s', 'PeriodwiseStage2TimeLimit_s'});
for Period_Index = 1:numel(Expected_Period_Counts)
    Period_Count = Expected_Period_Counts(Period_Index);
    Is_Period = Fig9_Data.PeriodCount == Period_Count;
    Is_AG = Is_Period & Fig9_Data.Formulation == "Aggregated";
    Is_PW = Is_Period & Fig9_Data.Formulation == "Period-wise";
    if nnz(Is_AG) ~= 1 || nnz(Is_PW) ~= 1
        error('Fig9:IncompleteFormulationPair', ...
            'Expected one AG and one PW result at T=%d.', Period_Count);
    end
    AG_Row = Fig9_Data(Is_AG, :);
    PW_Row = Fig9_Data(Is_PW, :);
    Period_Summary.AggregatedSolveTime_s(Period_Index) = ...
        AG_Row.TotalSolveTime_s;
    Period_Summary.PeriodwiseSolveTime_s(Period_Index) = ...
        PW_Row.TotalSolveTime_s;
    Period_Summary.AggregatedFinalMIPGap(Period_Index) = ...
        AG_Row.FinalMIPGap;
    Period_Summary.PeriodwiseFinalMIPGap(Period_Index) = ...
        PW_Row.FinalMIPGap;
    Period_Summary.AggregatedStage1TimeLimit_s(Period_Index) = ...
        AG_Row.Stage1TimeLimit_s;
    Period_Summary.AggregatedStage2TimeLimit_s(Period_Index) = ...
        AG_Row.Stage2TimeLimit_s;
    Period_Summary.PeriodwiseStage1TimeLimit_s(Period_Index) = ...
        PW_Row.Stage1TimeLimit_s;
    Period_Summary.PeriodwiseStage2TimeLimit_s(Period_Index) = ...
        PW_Row.Stage2TimeLimit_s;
    if AG_Row.ReachedTarget && PW_Row.ReachedTarget
        Period_Summary.PW_AG_SolutionTimeRatio(Period_Index) = ...
            PW_Row.TotalSolveTime_s/AG_Row.TotalSolveTime_s;
    elseif AG_Row.ReachedTarget && PW_Row.Censored
        Period_Summary.PW_AG_TargetTimeRatioLowerBound(Period_Index) = ...
            PW_Row.TotalSolveTime_s/AG_Row.TotalSolveTime_s;
    end
end
end

function Stage = read_stage_result( ...
    File_Path, Expected_Period_Count, Expected_Formulation, Expected_Stage)
%% 读取实际求解器时间、停止状态及阶段配置。

if ~isfile(File_Path)
    error('Fig9:MissingStageResult', ...
        'Finalized IV-C results are required for Fig. 9. Missing: %s', ...
        File_Path);
end
Loaded = load(File_Path, 'Result');
if ~isfield(Loaded, 'Result') || ~isstruct(Loaded.Result)
    error('Fig9:MissingResult', ...
        'Finalized IV-C results are required for Fig. 9. Missing Result: %s', ...
        File_Path);
end
Result = Loaded.Result;
if ~isfield(Result, 'CONF') || ~isstruct(Result.CONF) || ...
        ~isfield(Result.CONF, 'PeriodCount') || ...
        ~isscalar(Result.CONF.PeriodCount) || ...
        Result.CONF.PeriodCount ~= Expected_Period_Count
    error('Fig9:PeriodCountMismatch', ...
        'Finalized IV-C results are required for Fig. 9. Invalid T: %s', ...
        File_Path);
end
if ~isfield(Result.CONF, 'SecurityFormulation') || ...
        lower(string(Result.CONF.SecurityFormulation)) ~= Expected_Formulation
    error('Fig9:FormulationMismatch', ...
        ['Finalized IV-C results are required for Fig. 9. ', ...
        'Formulation mismatch: %s'], File_Path);
end
if ~isfield(Result.CONF, 'SolveStage') || ...
        lower(string(Result.CONF.SolveStage)) ~= Expected_Stage
    error('Fig9:StageMismatch', ...
        ['Finalized IV-C results are required for Fig. 9. ', ...
        'Expected %s result but CONF.SolveStage does not match: %s'], ...
        Expected_Stage, File_Path);
end
if ~isfield(Result, 'Diagnostics') || ...
        ~isstruct(Result.Diagnostics) || ...
        ~all(isfield(Result.Diagnostics, ...
        {'problem', 'info', 'solvertime', 'mip_gap', 'has_incumbent'}))
    error('Fig9:MissingTerminalDiagnostics', ...
        ['Finalized IV-C results are required for Fig. 9. ', ...
        'Terminal diagnostics are missing: %s'], File_Path);
end

Diagnostics = Result.Diagnostics;
if ~isscalar(Diagnostics.has_incumbent) || ...
        ~logical(Diagnostics.has_incumbent)
    error('Fig9:NoIncumbent', ...
        ['No feasible incumbent is recorded in %s. ', ...
        'Inspect the solver result; this script does not infer infeasibility.'], ...
        File_Path);
end
if ~isscalar(Diagnostics.problem) || ~isfinite(Diagnostics.problem) || ...
        ~ischar(Diagnostics.info) && ...
        ~(isstring(Diagnostics.info) && isscalar(Diagnostics.info)) || ...
        strlength(string(Diagnostics.info)) == 0
    error('Fig9:MissingTerminalStatus', ...
        'Finalized IV-C results are required for Fig. 9. Status missing: %s', ...
        File_Path);
end
Info = string(Diagnostics.info);
Is_Success = Diagnostics.problem == 0;
Is_Time_Limit = Diagnostics.problem == 3 && ...
    (contains(lower(Info), 'time limit') || ...
    contains(lower(Info), 'maximum iterations'));
if ~(Is_Success || Is_Time_Limit)
    error('Fig9:UnrecognizedTerminalStatus', ...
        ['Solver terminal status in %s is not a recognized completed ', ...
        'or time-limit result (%g: %s).'], ...
        File_Path, Diagnostics.problem, Info);
end
if ~isscalar(Diagnostics.solvertime) || ...
        ~isfinite(Diagnostics.solvertime) || Diagnostics.solvertime <= 0 || ...
        ~isscalar(Diagnostics.mip_gap) || ...
        ~isfinite(Diagnostics.mip_gap) || Diagnostics.mip_gap < 0
    error('Fig9:InvalidSolverMetrics', ...
        'Final solver time or MIP gap is missing/invalid: %s', File_Path);
end
if ~isfield(Result.CONF, 'solver') || ...
        ~isstruct(Result.CONF.solver) || ...
        ~isfield(Result.CONF.solver, 'name') || ...
        ~isfield(Result.CONF.solver, 'options')
    error('Fig9:MissingSolverConfiguration', ...
        'Stage-wise solver configuration is missing: %s', File_Path);
end
Solver_Backend = lower(string(Result.CONF.solver.name));
if ~isscalar(Solver_Backend) || ...
        ~isfield(Result.CONF.solver.options, char(Solver_Backend))
    error('Fig9:MissingBackendOptions', ...
        'Active backend options are missing in %s.', File_Path);
end
Backend_Options = Result.CONF.solver.options.(char(Solver_Backend));
if ~isfield(Backend_Options, 'TimeLimit')
    error('Fig9:MissingTimeLimit', ...
        'Actual stage time limit is missing in %s.', File_Path);
end
Configured_MIP_Gap = Backend_Options.MIPGap;
if ~isscalar(Backend_Options.TimeLimit) || ...
        ~isfinite(Backend_Options.TimeLimit) || ...
        Backend_Options.TimeLimit <= 0
    error('Fig9:InvalidTimeLimit', ...
        'Actual stage time limit is invalid in %s.', File_Path);
end
if Expected_Stage == "optimality-proof" && ...
        (~isscalar(Configured_MIP_Gap) || ...
        ~isfinite(Configured_MIP_Gap) || Configured_MIP_Gap <= 0)
    error('Fig9:MissingTargetGap', ...
        'Stage-2 target MIP gap is missing or invalid: %s', File_Path);
end

Stage = struct();
Stage.Result = Result;
Stage.FilePath = File_Path;
Stage.SolverTime_s = double(Diagnostics.solvertime);
Stage.MIPGap = double(Diagnostics.mip_gap);
Stage.HasIncumbent = logical(Diagnostics.has_incumbent);
Stage.Problem = double(Diagnostics.problem);
Stage.Info = char(Info);
Stage.SolverBackend = char(Solver_Backend);
Stage.TimeLimit_s = double(Backend_Options.TimeLimit);
Stage.ConfiguredMIPGap = double(Configured_MIP_Gap);
end

function Formulation = expected_formulation_value(Formulation_Key)
%% 将AG/PW归档标记映射为对应的安全约束表示。
if Formulation_Key == "AG"
    Formulation = "aggregated";
else
    Formulation = "periodwise";
end
end

function print_fig9_diagnostics(Period_Summary)
%% 输出阶段缺失、删失时间及最终间隙的归档诊断。
fprintf('\nFig. 9 solver-time diagnostics:\n');
for Period_Index = 1:height(Period_Summary)
    Row = Period_Summary(Period_Index, :);
    fprintf(['T=%2d | AG %.3f s (gap %.4f%%), PW %.3f s (gap %.4f%%) | ', ...
        'PW/AG Stage-1/2 limits: AG %.0f/%.0f s, PW %.0f/%.0f s\n'], ...
        Row.PeriodCount, Row.AggregatedSolveTime_s, ...
        100*Row.AggregatedFinalMIPGap, Row.PeriodwiseSolveTime_s, ...
        100*Row.PeriodwiseFinalMIPGap, ...
        Row.AggregatedStage1TimeLimit_s, Row.AggregatedStage2TimeLimit_s, ...
        Row.PeriodwiseStage1TimeLimit_s, Row.PeriodwiseStage2TimeLimit_s);
    if isfinite(Row.PW_AG_SolutionTimeRatio)
        fprintf('  PW/AG solution-time ratio = %.4f\n', ...
            Row.PW_AG_SolutionTimeRatio);
    elseif isfinite(Row.PW_AG_TargetTimeRatioLowerBound)
        fprintf(['  T=%2d PW/AG solver-time ratio lower bound = %.4f ', ...
            '(PW target gap not reached)\n'], Row.PeriodCount, ...
            Row.PW_AG_TargetTimeRatioLowerBound);
    end
end
end
