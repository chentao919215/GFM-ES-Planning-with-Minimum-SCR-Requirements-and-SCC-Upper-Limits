%% GFM-ES虚拟阻抗限流状态验证。
% 本文件集中展示验证过程；临时设置由局部函数的清理对象恢复。
% 使用正式模型顶层的有限电网阻抗，并按实测PCC电压验收。

%% 1. 设置验证选项
Validation_Options = struct('Confirm_Times_s', [0.005 0.010 0.020]);

%% 2. 执行验证并保存结果
[Validation_Result, Result_File] = run_validation(Validation_Options);
Project_Root = find_project_root(mfilename('fullpath'));
Figure_File = fullfile(Project_Root, 'figs', 'equipment', 'GFM', ...
    'GFM_VI_State_Validation.fig');
Figure_Handle = plot_gfm_vi_state_validation( ...
    Validation_Result, Figure_File, figure_style('review'));
assert(Validation_Result.AllAcceptancePassed, 'GFMValidation:AcceptanceFailed', ...
    '当前参数工况未通过全部状态验收，请查看已归档的检查结果。');

% 主验证过程与局部辅助函数
function [ValidationResult, Result_File] = run_validation(Options)
%% 编排模型验证与数值结果归档，绘图由独立入口负责。
if nargin < 1
    Options = struct();
end
Project_Root = find_project_root(mfilename('fullpath'));
% 按参数源定义的连续时段依次运行正式模型并验证：
% Case A（未触发）、Case B（触发并锁存）和 Case C（恢复退出）。
% 扫描5/10/20 ms连续恢复与重新武装确认时间，保存MAT与CSV。
% 模型参数由初始化入口提供，图件由独立绘图函数生成。

Result_Dir = fullfile(Project_Root, 'results', 'equipment', 'GFM');
if isfield(Options, 'Result_Directory')
    Result_Dir = Options.Result_Directory;
end
if ~isfolder(Result_Dir)
    mkdir(Result_Dir);
end

Model_File = fullfile(Project_Root, 'simulink', 'models', ...
    'Grid_Forming_Inverters.slx');
Parameter_File = fullfile(Project_Root, 'code', 'scripts', 'equipment', ...
    'initialization', 'initialize_gfm_model.m');

assert(isfile(Model_File), 'GFM model was not found: %s', Model_File);
assert(isfile(Parameter_File), ...
    'Formal GFM parameter script was not found: %s', Parameter_File);
addpath(genpath(fullfile(Project_Root, 'code', 'functions')));
File_Generation_Cleanup = configure_simulink_file_generation(Project_Root); %#ok<NASGU>

run(Parameter_File);

% 本验证需要正常、深跌落、恢复的电源指令；这些是算例前提，
% 实际触发和恢复仍按仿真测得的PCC电压、电流及状态验收。
assert(GFM_GridSource.CaseA.SourceVoltage_pu >= GFM_VI.U_boundary_pu && ...
    GFM_GridSource.CaseB.SourceVoltage_pu < GFM_VI.U_boundary_pu && ...
    GFM_GridSource.CaseC.SourceVoltage_pu >= GFM_VI.U_boundary_pu, ...
    'GFMValidation:InvalidStateScenario', ...
    '状态验证的电源指令须依次表示正常、故障和恢复工况。');

Model_Name = 'Grid_Forming_Inverters';
Was_Loaded = bdIsLoaded(Model_Name);
load_system(Model_File);
Model_Cleanup = onCleanup(@() close_model(Model_Name, Was_Loaded)); %#ok<NASGU>
Source_Block = [Model_Name '/Three-Phase Source'];
Interface_Block = [Model_Name '/Three-Phase' newline 'Grid Impedance'];
assert(getSimulinkBlockHandle(Source_Block) > 0, ...
    'The formal programmable three-phase source was not found.');
assert(getSimulinkBlockHandle(Interface_Block) > 0, ...
    'GFMValidation:MissingGridImpedance', ...
    '当前模型缺少有限电网阻抗：%s。', Interface_Block);
assert(strcmp(get_param(Interface_Block, 'Resistance'), ...
    'Rg') && ...
    strcmp(get_param(Interface_Block, 'Inductance'), ...
    'Lg'), ...
    'The grid-impedance block is not linked to formal parameters.');

Confirm_Candidates = [0.005, 0.010, 0.020];
if isfield(Options, 'Confirm_Times_s')
    Confirm_Candidates = Options.Confirm_Times_s;
end
Scan_Results = repmat(empty_result(), numel(Confirm_Candidates), 1);

fprintf('\n=== GFM sequential state validation ===\n');
fprintf('Model: %s\n', Model_File);
fprintf(['External grid: R=%.6f ohm (%.6f p.u.), ' ...
    'L=%.9f H (X=%.6f p.u.).\n'], ...
    GFM_GridImpedance.R_ohm, GFM_GridImpedance.R_pu, ...
    GFM_GridImpedance.L_H, GFM_GridImpedance.X_pu);
fprintf('Source command: %.3f -> %.3f -> %.3f p.u.\n', ...
    GFM_GridSource.CaseA.SourceVoltage_pu, ...
    GFM_GridSource.CaseB.SourceVoltage_pu, ...
    GFM_GridSource.CaseC.SourceVoltage_pu);
fprintf('Ub=%.6f p.u.; Ilim=%.6f p.u.; Xvir=%.6f p.u.\n', ...
    GFM_VI.U_boundary_pu, GFM_VI.I_switch_threshold_pu, ...
    GFM_VI.X_vir_device_pu);

for Candidate_Index = 1:numel(Confirm_Candidates)
    Confirm_Time = Confirm_Candidates(Candidate_Index);
    Simulation_Output = run_formal_sequence( ...
        Model_Name, Confirm_Time, GFM_VI, GFM_Sim.t_stop);
    Scan_Results(Candidate_Index) = analyze_formal_sequence( ...
        Simulation_Output, Confirm_Time, GFM_GridSource, GFM_VI, ...
        GFM_GridImpedance);
    print_transitions(Scan_Results(Candidate_Index));
end

Selected_Index = find([Scan_Results.Passed], 1, 'first');
if isempty(Selected_Index)
    [~, Plot_Index] = min([Scan_Results.TransitionCount]);
    Selected_Confirm_Time = NaN;
    Selection_Note = [ ...
        "No tested confirmation time passed all checks. " ...
        "The scan stopped at 20 ms."];
else
    Plot_Index = Selected_Index;
    Selected_Confirm_Time = Confirm_Candidates(Selected_Index);
    Selection_Note = sprintf( ...
        'Shortest passing confirmation time: %.3f s.', ...
        Selected_Confirm_Time);
end

Plot_Result = Scan_Results(Plot_Index);
Summary_Table = build_summary_table(Plot_Result, GFM_GridSource);
resultFile = fullfile(Result_Dir, ...
    'GFM_VI_State_Validation_Result.mat');
Summary_File = fullfile(Result_Dir, ...
    'GFM_VI_State_Validation_Summary.csv');

ValidationResult = struct();
ValidationResult.GeneratedAt = datetime('now', ...
    'TimeZone', 'Asia/Shanghai');
ValidationResult.ModelFile = Model_File;
ValidationResult.ParameterFile = Parameter_File;
ValidationResult.ValidationTopology = [ ...
    'Programmable external source behind the top-level finite RL grid ' ...
    'impedance; acceptance uses measured converter-terminal PCC voltage'];
ValidationResult.GridImpedance = GFM_GridImpedance;
ValidationResult.GridSource = GFM_GridSource;
ValidationResult.U_boundary_pu = GFM_VI.U_boundary_pu;
ValidationResult.I_switch_threshold_pu = ...
    GFM_VI.I_switch_threshold_pu;
ValidationResult.X_vir_device_pu = GFM_VI.X_vir_device_pu;
ValidationResult.ReleaseConfirmCandidates = Confirm_Candidates;
ValidationResult.RearmConfirmCandidates = Confirm_Candidates;
ValidationResult.SelectedReleaseConfirmTime = Selected_Confirm_Time;
ValidationResult.SelectedRearmConfirmTime = Selected_Confirm_Time;
ValidationResult.ConfiguredReleaseConfirmTime = ...
    GFM_VI.ReleaseConfirmTime;
ValidationResult.ConfiguredRearmConfirmTime = ...
    GFM_VI.RearmConfirmTime;
ValidationResult.SelectionNote = Selection_Note;
ValidationResult.CaseA = Plot_Result.CaseAChecks;
ValidationResult.CaseB = Plot_Result.CaseBChecks;
ValidationResult.CaseC = Plot_Result.CaseCChecks;
ValidationResult.ConfirmationScan = Scan_Results;
ValidationResult.SelectedResult = Plot_Result;
ValidationResult.Summary = Summary_Table;
ValidationResult.AllAcceptancePassed = ...
    ~isnan(Selected_Confirm_Time) && Plot_Result.Passed && ...
    abs(GFM_VI.ReleaseConfirmTime-Selected_Confirm_Time) < 1e-12 && ...
    abs(GFM_VI.RearmConfirmTime-Selected_Confirm_Time) < 1e-12;

save(resultFile, 'ValidationResult', '-v7.3');
writetable(Summary_Table, Summary_File, 'Encoding', 'UTF-8');

fprintf('\n=== Sequential state-validation summary ===\n');
disp(Summary_Table);
fprintf('%s\n', Selection_Note);
fprintf('Configured confirmation times: release %.3f s, rearm %.3f s.\n', ...
    GFM_VI.ReleaseConfirmTime, GFM_VI.RearmConfirmTime);
fprintf('MAT: %s\n', resultFile);
fprintf('CSV: %s\n', Summary_File);

Result_File = resultFile;
end

% 局部辅助函数
function Simulation_Output = run_formal_sequence( ...
    Model_Name, Confirm_Time, Base_Vi, Stop_Time)
%% 按正式电源时序及确认时间运行GFM状态验证。
Release_Block = [Model_Name ...
    '/GFM_1/Future_Extensions_Hook/VI_Release_Confirm_Time'];
Rearm_Block = [Model_Name ...
    '/GFM_1/Future_Extensions_Hook/VI_Rearm_Confirm_Time'];
Case_Vi = Base_Vi;
Case_Vi.ReleaseConfirmTime = Confirm_Time;
Case_Vi.RearmConfirmTime = Confirm_Time;
Simulation_Input = Simulink.SimulationInput(Model_Name);
Simulation_Input = Simulation_Input.setVariable('GFM_VI', Case_Vi);
Simulation_Input = Simulation_Input.setBlockParameter( ...
    Release_Block, 'Value', sprintf('%.17g', Confirm_Time));
Simulation_Input = Simulation_Input.setBlockParameter( ...
    Rearm_Block, 'Value', sprintf('%.17g', Confirm_Time));
Simulation_Input = Simulation_Input.setModelParameter( ...
    'StopTime', sprintf('%.17g', Stop_Time), ...
    'ReturnWorkspaceOutputs', 'on');
Simulation_Output = sim(Simulation_Input);
end

function result = analyze_formal_sequence(Simulation_Output, ...
    Confirm_Time, Grid_Source, vi, PCC_Interface)
%% 按实测电压、电流和状态记录验收三个连续工况。
logs = Simulation_Output.logsout;
Slim_Signal = get_signal(logs, 'Slim');
Current_Signal = get_signal(logs, 'I_GFM_mag_pu');
Voltage_Signal = get_signal(logs, 'U_PCC_pu');
Reactance_Signal = get_signal(logs, 'X_vir_applied_pu');
Delta_D_Signal = get_signal(logs, 'DeltaUVI_d');
Delta_Q_Signal = get_signal(logs, 'DeltaUVI_q');
Release_Timer_Signal = get_signal(logs, ...
    'ReleaseConfirmElapsed_s');
Rearm_Armed_Signal = get_signal(logs, 'RearmArmed');
Rearm_Timer_Signal = get_signal(logs, ...
    'RearmConfirmElapsed_s');

time = double(Slim_Signal.Time(:));
slim = double(Slim_Signal.Data(:));
current = interpolate_signal(Current_Signal, time, 'previous');
voltage = interpolate_signal(Voltage_Signal, time, 'previous');
Applied_Reactance = interpolate_signal( ...
    Reactance_Signal, time, 'previous');
Delta_D = interpolate_signal(Delta_D_Signal, time, 'previous');
Delta_Q = interpolate_signal(Delta_Q_Signal, time, 'previous');
Release_Timer = interpolate_signal( ...
    Release_Timer_Signal, time, 'linear');
Rearm_Armed = interpolate_signal( ...
    Rearm_Armed_Signal, time, 'previous');
Rearm_Timer = interpolate_signal( ...
    Rearm_Timer_Signal, time, 'linear');

Source_Voltage_Command = interp1( ...
    Grid_Source.TimeValues_s(:), ...
    Grid_Source.Amplitudes_pu(:), time, 'linear', 'extrap');

Transition_Index = find(diff(slim) ~= 0) + 1;
Transition_Times = time(Transition_Index);
Transition_Directions = strings(numel(Transition_Index), 1);
for Transition_Number = 1:numel(Transition_Index)
    if slim(Transition_Index(Transition_Number)-1) < 0.5 && ...
            slim(Transition_Index(Transition_Number)) >= 0.5
        Transition_Directions(Transition_Number) = "OFF->ON";
    else
        Transition_Directions(Transition_Number) = "ON->OFF";
    end
end
transitions = table(Transition_Times, Transition_Directions, ...
    'VariableNames', {'Time_s', 'Direction'});

On_Times = Transition_Times(Transition_Directions == "OFF->ON");
Off_Times = Transition_Times(Transition_Directions == "ON->OFF");
First_Trigger_Time = first_or_nan(On_Times);
First_Exit_Time = first_or_nan(Off_Times);
Fault_Start = Grid_Source.CaseB.StartTime_s;
Fault_Clear = Grid_Source.CaseC.StartTime_s;

Case_A_Mask = time >= max(1.0, Grid_Source.CaseA.EndTime_s-0.5) & ...
    time < Grid_Source.CaseA.EndTime_s;
Case_B_Mask = time >= Fault_Start & time < Fault_Clear;
Late_Case_B_Mask = time >= Fault_Clear-0.25 & time < Fault_Clear;
Case_C_Mask = time >= Fault_Clear & ...
    time <= Grid_Source.CaseC.EndTime_s;

Finite_Signals = all(isfinite(current)) && ...
    all(isfinite(voltage)) && all(isfinite(slim)) && ...
    all(isfinite(Applied_Reactance)) && ...
    all(isfinite(Delta_D)) && all(isfinite(Delta_Q)) && ...
    all(isfinite(Release_Timer)) && all(isfinite(Rearm_Timer));

B_Transitions = Transition_Times >= Fault_Start & ...
    Transition_Times < Fault_Clear;
C_Transitions = Transition_Times >= Fault_Clear;
B_Off_Transitions = B_Transitions & ...
    Transition_Directions == "ON->OFF";
Fault_Current_Peak = max(current(Case_B_Mask));
Late_Fault_Current_Mean = mean(current(Late_Case_B_Mask));
Full_Reactance_Applied = any(slim >= 0.5) && ...
    max(abs(Applied_Reactance(slim >= 0.5) - ...
    vi.X_vir_device_pu)) < 1e-6;
Latched_Below_Threshold = any(slim >= 0.5 & ...
    current < vi.I_switch_threshold_pu);

Timer_Tolerance = max(2e-4, Confirm_Time*0.02);

Voltage_Above_Boundary = voltage(Case_C_Mask) >= vi.U_boundary_pu;
Boundary_Crossings = nnz(diff(Voltage_Above_Boundary) ~= 0);
Release_Start_Time = timer_start( ...
    time, Release_Timer, First_Exit_Time, Confirm_Time);
Rearm_Rise_Index = find(diff(Rearm_Armed >= 0.5) > 0) + 1;
Rearm_Rise_Times = time(Rearm_Rise_Index);
Final_Rearm_Time = first_or_nan( ...
    Rearm_Rise_Times(Rearm_Rise_Times >= First_Exit_Time));
Rearm_Start_Time = timer_start( ...
    time, Rearm_Timer, Final_Rearm_Time, Confirm_Time);
% 有限电网阻抗下PCC不等于外部电源指令，按实测电压检验各工作区。
Release_Delay = First_Exit_Time-Release_Start_Time;

Case_A_Checks = struct( ...
    'CurrentBelowThreshold', ...
    max(current(Case_A_Mask)) < vi.I_switch_threshold_pu, ...
    'SlimAlwaysOff', all(slim(Case_A_Mask) < 0.5), ...
    'VirtualReactanceOff', ...
    max(abs(Applied_Reactance(Case_A_Mask))) < 1e-9, ...
    'MeasuredPCCAboveBoundary', all(voltage(Case_A_Mask) >= vi.U_boundary_pu), ...
    'NoCaseATransitions', ~any(Transition_Times < Fault_Start), ...
    'FiniteSignals', Finite_Signals);

Case_B_Checks = struct( ...
    'CurrentReachedThreshold', ...
    Fault_Current_Peak >= vi.I_switch_threshold_pu, ...
    'ExactlyOneFaultTrigger', ...
    nnz(B_Transitions) == 1 && isscalar(On_Times), ...
    'NoFaultExit', ~any(B_Off_Transitions), ...
    'MeasuredFaultPCCBelowBoundary', ...
    all(voltage(Late_Case_B_Mask) < vi.U_boundary_pu), ...
    'FullReactanceApplied', Full_Reactance_Applied, ...
    'CurrentDeclinedAfterInsertion', ...
    Late_Fault_Current_Mean < Fault_Current_Peak-0.05, ...
    'LatchedBelowThreshold', Latched_Below_Threshold, ...
    'FiniteSignals', Finite_Signals);

Correct_Directions = numel(Transition_Directions) == 2 && ...
    Transition_Directions(1) == "OFF->ON" && ...
    Transition_Directions(2) == "ON->OFF";
Case_C_Checks = struct( ...
    'ExactlyTwoTransitionsOverall', ...
    numel(Transition_Index) == 2, ...
    'CorrectTransitionDirections', Correct_Directions, ...
    'ExactlyOneRecoveryExit', nnz(C_Transitions) == 1, ...
    'ReleaseAfterContinuousConfirmation', ...
    isfinite(Release_Delay) && ...
    Release_Delay >= Confirm_Time-Timer_Tolerance && ...
    Release_Delay <= Confirm_Time+2e-3, ...
    'FinalStateOff', slim(end) < 0.5, ...
    'FinalRearmArmed', Rearm_Armed(end) >= 0.5, ...
    'FinalVoltageRecovered', voltage(end) >= vi.U_boundary_pu, ...
    'FinalCurrentNormal', ...
    current(end) < vi.I_switch_threshold_pu, ...
    'NoExtraTransitionAfterExit', ...
    nnz(Transition_Times > First_Exit_Time) == 0, ...
    'FiniteSignals', Finite_Signals);

Case_A_Passed = all(structfun(@logical, Case_A_Checks));
Case_B_Passed = all(structfun(@logical, Case_B_Checks));
Case_C_Passed = all(structfun(@logical, Case_C_Checks));

result = empty_result();
result.CaseName = sprintf('Sequential A/B/C (%d ms)', ...
    round(1000*Confirm_Time));
result.CaseType = "C";
result.FaultSetting = sprintf( ...
    'U_source %.3f -> %.3f -> %.3f p.u.; %.3f/%.3f/%.3f s', ...
    Grid_Source.CaseA.SourceVoltage_pu, ...
    Grid_Source.CaseB.SourceVoltage_pu, ...
    Grid_Source.CaseC.SourceVoltage_pu, ...
    Grid_Source.CaseA.Duration_s, Grid_Source.CaseB.Duration_s, ...
    Grid_Source.CaseC.Duration_s);
result.SourceSag_pu = Grid_Source.CaseB.SourceVoltage_pu;
result.GridInductance_H = PCC_Interface.L_H;
result.FaultStartTime = Fault_Start;
result.FaultClearTime = Fault_Clear;
result.VoltageFallTime_s = Grid_Source.TransitionTime_s;
result.VoltageRecoveryRampTime_s = Grid_Source.TransitionTime_s;
result.ReleaseConfirmTime = Confirm_Time;
result.RearmConfirmTime = Confirm_Time;
result.TransitionCount = numel(Transition_Index);
result.Transitions = transitions;
result.FirstTriggerTime = First_Trigger_Time;
result.FirstExitTime = First_Exit_Time;
result.FinalExitTime = last_or_nan(Off_Times);
result.ReleaseConfirmStartTime = Release_Start_Time;
result.RearmConfirmStartTime = Rearm_Start_Time;
result.FinalRearmTime = Final_Rearm_Time;
result.PostFaultBoundaryCrossings = Boundary_Crossings;
result.FinalSlim = slim(end);
result.FinalVoltage_pu = voltage(end);
result.FinalCurrent_pu = current(end);
result.MaximumCurrent_pu = max(current);
result.FaultCurrentPeak_pu = Fault_Current_Peak;
result.LateFaultCurrentMean_pu = Late_Fault_Current_Mean;
result.Passed = Case_A_Passed && Case_B_Passed && Case_C_Passed;
result.CaseAPassed = Case_A_Passed;
result.CaseBPassed = Case_B_Passed;
result.CaseCPassed = Case_C_Passed;
result.CaseAChecks = Case_A_Checks;
result.CaseBChecks = Case_B_Checks;
result.CaseCChecks = Case_C_Checks;
result.Notes = combined_notes( ...
    Case_A_Checks, Case_B_Checks, Case_C_Checks);
result.Data = reduce_data(time, current, voltage, slim, ...
    Applied_Reactance, Delta_D, Delta_Q, Release_Timer, ...
    Rearm_Armed, Rearm_Timer, Source_Voltage_Command, ...
    Transition_Index);
end

function Start_Time = timer_start( ...
    time, timer, Event_Time, Confirm_Time)
%% 根据事件位置回溯连续确认计时的起点。
Start_Time = NaN;
if ~isfinite(Event_Time)
    return;
end
Event_Index = find(time >= Event_Time, 1, 'first');
if isempty(Event_Index)
    return;
end
tolerance = max(1e-9, Confirm_Time*1e-5);
Search_Index = max(1, Event_Index-1);
while Search_Index > 1 && timer(Search_Index) > tolerance
    Search_Index = Search_Index-1;
end
if Search_Index < Event_Index-1
    Start_Time = time(Search_Index+1);
end
end

function signal = get_signal(logs, Signal_Name)
%% 从日志数据集中读取指定信号的timeseries。
element = logs.get(Signal_Name);
assert(~isempty(element), ...
    'Required logged signal was not found: %s', Signal_Name);
signal = element.Values;
end

function values = interpolate_signal(signal, Query_Time, method)
%% 去除重复时刻后，将记录信号插值到共同时间轴。
Source_Time = double(signal.Time(:));
Source_Data = double(signal.Data(:));
[Source_Time, uniqueIndex] = unique(Source_Time, 'last');
Source_Data = Source_Data(uniqueIndex);
values = interp1(Source_Time, Source_Data, ...
    Query_Time, method, 'extrap');
end

function value = first_or_nan(values)
%% 返回首个事件时刻，无事件时返回NaN。
if isempty(values)
    value = NaN;
else
    value = values(1);
end
end

function value = last_or_nan(values)
%% 返回最后一个事件时刻，无事件时返回NaN。
if isempty(values)
    value = NaN;
else
    value = values(end);
end
end

function notes = combined_notes(A_Checks, B_Checks, C_Checks)
%% 合并三个工况中的未通过原因。
notes = strings(0, 1);
groups = {A_Checks, B_Checks, C_Checks};
labels = ["A", "B", "C"];
for Group_Index = 1:numel(groups)
    names = string(fieldnames(groups{Group_Index}));
    values = struct2cell(groups{Group_Index});
    failed = names(~cellfun(@logical, values));
    if ~isempty(failed)
        notes(end+1, 1) = labels(Group_Index) + ...
            " failed: " + strjoin(failed, '; '); %#ok<AGROW>
    end
end
if isempty(notes)
    notes = "Passed all automatic checks";
else
    notes = strjoin(notes, ' | ');
end
end

function Reduced_Data = reduce_data(time, current, voltage, slim, ...
    Applied_Reactance, Delta_D, Delta_Q, Release_Timer, Rearm_Armed, ...
    Rearm_Timer, Source_Voltage_Command, Transition_Index)
%% 按保留事件和曲线形状的索引精简归档时间序列。
Maximum_Points = 20000;
stride = max(1, ceil(numel(time)/Maximum_Points));
Keep_Index = (1:stride:numel(time))';
Keep_Index = unique([Keep_Index; numel(time); ...
    Transition_Index; Transition_Index-1]);
Keep_Index = Keep_Index( ...
    Keep_Index >= 1 & Keep_Index <= numel(time));

Reduced_Data = struct();
Reduced_Data.Time_s = time(Keep_Index);
Reduced_Data.Current_pu = current(Keep_Index);
Reduced_Data.Voltage_pu = voltage(Keep_Index);
Reduced_Data.SourceVoltageCommand_pu = ...
    Source_Voltage_Command(Keep_Index);
Reduced_Data.Slim = slim(Keep_Index);
Reduced_Data.X_vir_applied_pu = Applied_Reactance(Keep_Index);
Reduced_Data.DeltaUVI_d = Delta_D(Keep_Index);
Reduced_Data.DeltaUVI_q = Delta_Q(Keep_Index);
Reduced_Data.ReleaseConfirmElapsed_s = Release_Timer(Keep_Index);
Reduced_Data.RearmArmed = Rearm_Armed(Keep_Index);
Reduced_Data.RearmConfirmElapsed_s = Rearm_Timer(Keep_Index);
end

function result = empty_result()
%% 初始化状态验证的工况、验收、事件与精简数据字段。
result = struct( ...
    'CaseName', "", 'CaseType', "", 'FaultSetting', "", ...
    'SourceSag_pu', NaN, 'GridInductance_H', NaN, ...
    'FaultStartTime', NaN, 'FaultClearTime', NaN, ...
    'VoltageFallTime_s', NaN, ...
    'VoltageRecoveryRampTime_s', NaN, ...
    'ReleaseConfirmTime', NaN, 'RearmConfirmTime', NaN, ...
    'TransitionCount', 0, 'Transitions', table(), ...
    'FirstTriggerTime', NaN, 'FirstExitTime', NaN, ...
    'FinalExitTime', NaN, 'ReleaseConfirmStartTime', NaN, ...
    'RearmConfirmStartTime', NaN, 'FinalRearmTime', NaN, ...
    'PostFaultBoundaryCrossings', 0, 'FinalSlim', NaN, ...
    'FinalVoltage_pu', NaN, 'FinalCurrent_pu', NaN, ...
    'MaximumCurrent_pu', NaN, 'FaultCurrentPeak_pu', NaN, ...
    'LateFaultCurrentMean_pu', NaN, 'Passed', false, ...
    'CaseAPassed', false, 'CaseBPassed', false, ...
    'CaseCPassed', false, 'CaseAChecks', struct(), ...
    'CaseBChecks', struct(), 'CaseCChecks', struct(), ...
    'Notes', "", 'Data', struct());
end

function print_transitions(result)
%% 输出当前工况检测到的状态跃迁及确认时间。
fprintf(['\n[%s] sag %.3f p.u.; grid L %.6f H; ' ...
    'confirm %.3f s\n'], ...
    result.CaseName, result.SourceSag_pu, ...
    result.GridInductance_H, result.ReleaseConfirmTime);
fprintf('Transitions: %d; A/B/C pass: %d/%d/%d\n', ...
    result.TransitionCount, result.CaseAPassed, ...
    result.CaseBPassed, result.CaseCPassed);
if isempty(result.Transitions)
    fprintf('No Slim transitions.\n');
else
    disp(result.Transitions);
end
fprintf('%s\n', result.Notes);
end

function Summary_Table = build_summary_table(result, Grid_Source)
%% 按三个连续工况生成验收摘要表。
Case_Name = ["Case A"; "Case B"; "Case C"];
Fault_Setting = string({ ...
    sprintf('U_source = %.3f p.u.; [%.3f, %.3f] s', ...
    Grid_Source.CaseA.SourceVoltage_pu, ...
    Grid_Source.CaseA.StartTime_s, Grid_Source.CaseA.EndTime_s); ...
    sprintf('U_source = %.3f p.u.; [%.3f, %.3f] s', ...
    Grid_Source.CaseB.SourceVoltage_pu, ...
    Grid_Source.CaseB.StartTime_s, Grid_Source.CaseB.EndTime_s); ...
    sprintf('U_source = %.3f p.u.; [%.3f, %.3f] s', ...
    Grid_Source.CaseC.SourceVoltage_pu, ...
    Grid_Source.CaseC.StartTime_s, Grid_Source.CaseC.EndTime_s)});

times = result.Transitions.Time_s;
directions = result.Transitions.Direction;
Transition_Count = [ ...
    nnz(times < Grid_Source.CaseB.StartTime_s); ...
    nnz(times >= Grid_Source.CaseB.StartTime_s & ...
    times < Grid_Source.CaseC.StartTime_s); ...
    result.TransitionCount];
First_Trigger_Time_s = [NaN; result.FirstTriggerTime; ...
    result.FirstTriggerTime];
Final_Exit_Time_s = [NaN; NaN; result.FinalExitTime];
Release_Confirm_Time_s = repmat(result.ReleaseConfirmTime, 3, 1);
passed = [result.CaseAPassed; ...
    result.CaseBPassed; result.CaseCPassed];
notes = [ ...
    "No trigger; Slim remains OFF"; ...
    "One OFF->ON; current falls below Ilim while Slim stays ON"; ...
    "Overall sequence has exactly OFF->ON and ON->OFF"];
Transition_Directions = [ ...
    ""; ...
    strjoin(directions(times >= Grid_Source.CaseB.StartTime_s & ...
    times < Grid_Source.CaseC.StartTime_s), ', '); ...
    strjoin(directions, ', ')];

Summary_Table = table(Case_Name, Fault_Setting, ...
    Transition_Count, Transition_Directions, ...
    First_Trigger_Time_s, Final_Exit_Time_s, ...
    Release_Confirm_Time_s, passed, notes, ...
    'VariableNames', {'CaseName', 'FaultSetting', ...
    'TransitionCount', 'TransitionDirections', ...
    'FirstTriggerTime_s', 'FinalExitTime_s', ...
    'ReleaseConfirmTime_s', 'Passed', 'Notes'});
end

function close_model(Model_Name, Was_Loaded)
%% 仅关闭本次调用新加载的模型，不保存临时修改。
if ~Was_Loaded && bdIsLoaded(Model_Name)
    close_system(Model_Name, 0);
end
