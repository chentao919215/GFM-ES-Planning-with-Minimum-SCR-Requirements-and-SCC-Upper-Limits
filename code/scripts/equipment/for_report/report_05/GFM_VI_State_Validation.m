ValidationResult.ReleaseConfirmCandidates = confirmCandidates;
ValidationResult.RearmConfirmCandidates = confirmCandidates;
ValidationResult.SelectedReleaseConfirmTime = selectedConfirmTime;
ValidationResult.SelectedRearmConfirmTime = selectedConfirmTime;
ValidationResult.ConfiguredReleaseConfirmTime = ...
    GFM_VI.ReleaseConfirmTime;
ValidationResult.ConfiguredRearmConfirmTime = ...
    GFM_VI.RearmConfirmTime;
ValidationResult.SelectionNote = selectionNote;
ValidationResult.CaseA = plotResult.CaseAChecks;
ValidationResult.CaseB = plotResult.CaseBChecks;
ValidationResult.CaseC = plotResult.CaseCChecks;
ValidationResult.CaseCRearmScan = scanResults;
ValidationResult.ConfirmationScan = scanResults;
ValidationResult.SelectedResult = plotResult;
ValidationResult.Summary = summaryTable;
ValidationResult.AllAcceptancePassed = ...
    ~isnan(selectedConfirmTime) && plotResult.Passed && ...
    abs(GFM_VI.ReleaseConfirmTime-selectedConfirmTime) < 1e-12 && ...
    abs(GFM_VI.RearmConfirmTime-selectedConfirmTime) < 1e-12;

save(resultFile, 'ValidationResult', '-v7.3');
writetable(summaryTable, summaryFile, 'Encoding', 'UTF-8');

fprintf('\n=== Sequential state-validation summary ===\n');
disp(summaryTable);
fprintf('%s\n', selectionNote);
fprintf('Configured confirmation times: release %.3f s, rearm %.3f s.\n', ...
    GFM_VI.ReleaseConfirmTime, GFM_VI.RearmConfirmTime);
fprintf('PNG: %s\n', pngFile);
fprintf('MAT: %s\n', resultFile);
fprintf('CSV: %s\n', summaryFile);

close_system(modelName, 0);
assert(ValidationResult.AllAcceptancePassed, ...
    'The configured formal model did not pass all sequential checks.');

%% Local functions
function simulationOutput = localRunFormalSequence( ...
        modelName, confirmTime, baseVI, stopTime)
    releaseBlock = [modelName ...
        '/GFM_1/Future_Extensions_Hook/VI_Release_Confirm_Time'];
    rearmBlock = [modelName ...
        '/GFM_1/Future_Extensions_Hook/VI_Rearm_Confirm_Time'];
    caseVI = baseVI;
    caseVI.ReleaseConfirmTime = confirmTime;
    caseVI.RearmConfirmTime = confirmTime;
    simulationInput = Simulink.SimulationInput(modelName);
    simulationInput = simulationInput.setVariable('GFM_VI', caseVI);
    simulationInput = simulationInput.setBlockParameter( ...
        releaseBlock, 'Value', sprintf('%.17g', confirmTime));
    simulationInput = simulationInput.setBlockParameter( ...
        rearmBlock, 'Value', sprintf('%.17g', confirmTime));
    simulationInput = simulationInput.setModelParameter( ...
        'StopTime', sprintf('%.17g', stopTime), ...
        'ReturnWorkspaceOutputs', 'on');
    simulationOutput = sim(simulationInput);
end

function result = localAnalyzeFormalSequence(simulationOutput, ...
        confirmTime, gridSource, vi, pccInterface)
    logs = simulationOutput.logsout;
    slimSignal = localGetSignal(logs, 'Slim');
    currentSignal = localGetSignal(logs, 'I_GFM_mag_pu');
    voltageSignal = localGetSignal(logs, 'U_PCC_pu');
    reactanceSignal = localGetSignal(logs, 'X_vir_applied_pu');
    deltaDSignal = localGetSignal(logs, 'DeltaUVI_d');
    deltaQSignal = localGetSignal(logs, 'DeltaUVI_q');
    releaseTimerSignal = localGetSignal(logs, ...
        'ReleaseConfirmElapsed_s');
    rearmArmedSignal = localGetSignal(logs, 'RearmArmed');
    rearmTimerSignal = localGetSignal(logs, ...
        'RearmConfirmElapsed_s');

    time = double(slimSignal.Time(:));
    slim = double(slimSignal.Data(:));
    current = localInterpolateSignal(currentSignal, time, 'previous');
    voltage = localInterpolateSignal(voltageSignal, time, 'previous');
    appliedReactance = localInterpolateSignal( ...
        reactanceSignal, time, 'previous');
    deltaD = localInterpolateSignal(deltaDSignal, time, 'previous');
    deltaQ = localInterpolateSignal(deltaQSignal, time, 'previous');
    releaseTimer = localInterpolateSignal( ...
        releaseTimerSignal, time, 'linear');
    rearmArmed = localInterpolateSignal( ...
        rearmArmedSignal, time, 'previous');
    rearmTimer = localInterpolateSignal( ...
        rearmTimerSignal, time, 'linear');

    sourceVoltageCommand = interp1( ...
        gridSource.TimeValues_s(:), ...
        gridSource.Amplitudes_pu(:), time, 'linear', 'extrap');

    transitionIndex = find(diff(slim) ~= 0) + 1;
    transitionTimes = time(transitionIndex);
    transitionDirections = strings(numel(transitionIndex), 1);
    for transitionNumber = 1:numel(transitionIndex)
        if slim(transitionIndex(transitionNumber)-1) < 0.5 && ...
                slim(transitionIndex(transitionNumber)) >= 0.5
            transitionDirections(transitionNumber) = "OFF->ON";
        else
            transitionDirections(transitionNumber) = "ON->OFF";
        end
    end
    transitions = table(transitionTimes, transitionDirections, ...
        'VariableNames', {'Time_s', 'Direction'});

    onTimes = transitionTimes(transitionDirections == "OFF->ON");
    offTimes = transitionTimes(transitionDirections == "ON->OFF");
    firstTriggerTime = localFirstOrNaN(onTimes);
    firstExitTime = localFirstOrNaN(offTimes);
    faultStart = gridSource.CaseB.StartTime_s;
    faultClear = gridSource.CaseC.StartTime_s;

    caseAMask = time >= max(1.0, gridSource.CaseA.EndTime_s-0.5) & ...
        time < gridSource.CaseA.EndTime_s;
    caseBMask = time >= faultStart & time < faultClear;
    lateCaseBMask = time >= faultClear-0.25 & time < faultClear;
    caseCMask = time >= faultClear & ...
        time <= gridSource.CaseC.EndTime_s;
    trackingMask = caseAMask | ...
        (time >= faultStart+0.5 & time < faultClear-0.1) | ...
        (time >= faultClear+0.5 & ...
        time <= gridSource.CaseC.EndTime_s);

    finiteSignals = all(isfinite(current)) && ...
        all(isfinite(voltage)) && all(isfinite(slim)) && ...
        all(isfinite(appliedReactance)) && ...
        all(isfinite(deltaD)) && all(isfinite(deltaQ)) && ...
        all(isfinite(releaseTimer)) && all(isfinite(rearmTimer));

    bTransitions = transitionTimes >= faultStart & ...
        transitionTimes < faultClear;
    cTransitions = transitionTimes >= faultClear;
    bOffTransitions = bTransitions & ...
        transitionDirections == "ON->OFF";
    faultCurrentPeak = max(current(caseBMask));
    lateFaultCurrentMean = mean(current(lateCaseBMask));
    fullReactanceApplied = any(slim >= 0.5) && ...
        max(abs(appliedReactance(slim >= 0.5) - ...
        vi.X_vir_device_pu)) < 1e-6;
    latchedBelowThreshold = any(slim >= 0.5 & ...
        current < vi.I_switch_threshold_pu);

    recoveryCondition = time >= faultClear & ...
        voltage >= vi.U_boundary_pu;
    recoveryStartTime = localFirstOrNaN(time(recoveryCondition));
    releaseDelay = firstExitTime-recoveryStartTime;
    timerTolerance = max(2e-4, confirmTime*0.02);

    voltageAboveBoundary = voltage(caseCMask) >= vi.U_boundary_pu;
    boundaryCrossings = nnz(diff(voltageAboveBoundary) ~= 0);
    releaseStartTime = localTimerStart( ...
        time, releaseTimer, firstExitTime, confirmTime);
    rearmRiseIndex = find(diff(rearmArmed >= 0.5) > 0) + 1;
    rearmRiseTimes = time(rearmRiseIndex);
    finalRearmTime = localFirstOrNaN( ...
        rearmRiseTimes(rearmRiseTimes >= firstExitTime));
    rearmStartTime = localTimerStart( ...
        time, rearmTimer, finalRearmTime, confirmTime);
    voltageTrackingError = max(abs( ...
        voltage(trackingMask)-sourceVoltageCommand(trackingMask)));

    caseAChecks = struct( ...
        'CurrentBelowThreshold', ...
        max(current(caseAMask)) < vi.I_switch_threshold_pu, ...
        'SlimAlwaysOff', all(slim(caseAMask) < 0.5), ...
        'VirtualReactanceOff', ...
        max(abs(appliedReactance(caseAMask))) < 1e-9, ...
        'PCCVoltageTracksCommand', voltageTrackingError < 5e-3, ...
        'NoCaseATransitions', ~any(transitionTimes < faultStart), ...
        'FiniteSignals', finiteSignals);

    caseBChecks = struct( ...
        'CurrentReachedThreshold', ...
        faultCurrentPeak >= vi.I_switch_threshold_pu, ...
        'ExactlyOneFaultTrigger', ...
        nnz(bTransitions) == 1 && numel(onTimes) == 1, ...
        'NoFaultExit', ~any(bOffTransitions), ...
        'FullReactanceApplied', fullReactanceApplied, ...
        'CurrentDeclinedAfterInsertion', ...
        lateFaultCurrentMean < faultCurrentPeak-0.05, ...
        'LatchedBelowThreshold', latchedBelowThreshold, ...
        'FiniteSignals', finiteSignals);

    correctDirections = numel(transitionDirections) == 2 && ...
        transitionDirections(1) == "OFF->ON" && ...
        transitionDirections(2) == "ON->OFF";
    caseCChecks = struct( ...
        'ExactlyTwoTransitionsOverall', ...
        numel(transitionIndex) == 2, ...
        'CorrectTransitionDirections', correctDirections, ...
        'ExactlyOneRecoveryExit', nnz(cTransitions) == 1, ...
        'ReleaseAfterContinuousConfirmation', ...
        isfinite(releaseDelay) && ...
        releaseDelay >= confirmTime-timerTolerance && ...
        releaseDelay <= confirmTime+2e-3, ...
        'FinalStateOff', slim(end) < 0.5, ...
        'FinalRearmArmed', rearmArmed(end) >= 0.5, ...
        'FinalVoltageRecovered', voltage(end) >= vi.U_boundary_pu, ...
        'FinalCurrentNormal', ...
        current(end) < vi.I_switch_threshold_pu, ...
        'NoExtraTransitionAfterExit', ...
        nnz(transitionTimes > firstExitTime) == 0, ...
        'FiniteSignals', finiteSignals);

    caseAPassed = all(structfun(@logical, caseAChecks));
    caseBPassed = all(structfun(@logical, caseBChecks));
    caseCPassed = all(structfun(@logical, caseCChecks));

    result = localEmptyResult();
    result.CaseName = sprintf('Sequential A/B/C (%d ms)', ...
        round(1000*confirmTime));
    result.CaseType = "C";
    result.FaultSetting = sprintf( ...
        'U_PCC %.3f -> %.3f -> %.3f p.u.; %.3f/%.3f/%.3f s', ...
        gridSource.CaseA.U_PCC_target_pu, ...
        gridSource.CaseB.U_PCC_target_pu, ...
        gridSource.CaseC.U_PCC_target_pu, ...
        gridSource.CaseA.Duration_s, gridSource.CaseB.Duration_s, ...
        gridSource.CaseC.Duration_s);
    result.SourceSag_pu = gridSource.CaseB.U_PCC_target_pu;
    result.GridInductance_H = pccInterface.L_H;
    result.FaultStartTime = faultStart;
    result.FaultClearTime = faultClear;
    result.VoltageFallTime_s = gridSource.TransitionTime_s;
    result.VoltageRecoveryRampTime_s = gridSource.TransitionTime_s;
    result.ReleaseConfirmTime = confirmTime;
    result.RearmConfirmTime = confirmTime;
    result.TransitionCount = numel(transitionIndex);
    result.Transitions = transitions;
    result.FirstTriggerTime = firstTriggerTime;
    result.FirstExitTime = firstExitTime;
    result.FinalExitTime = localLastOrNaN(offTimes);
    result.ReleaseConfirmStartTime = releaseStartTime;
    result.RearmConfirmStartTime = rearmStartTime;
    result.FinalRearmTime = finalRearmTime;
    result.PostFaultBoundaryCrossings = boundaryCrossings;
    result.FinalSlim = slim(end);
    result.FinalVoltage_pu = voltage(end);
    result.FinalCurrent_pu = current(end);
    result.MaximumCurrent_pu = max(current);
    result.FaultCurrentPeak_pu = faultCurrentPeak;
    result.LateFaultCurrentMean_pu = lateFaultCurrentMean;
    result.Passed = caseAPassed && caseBPassed && caseCPassed;
    result.CaseAPassed = caseAPassed;
    result.CaseBPassed = caseBPassed;
    result.CaseCPassed = caseCPassed;
    result.CaseAChecks = caseAChecks;
    result.CaseBChecks = caseBChecks;
    result.CaseCChecks = caseCChecks;
    result.Notes = localCombinedNotes( ...
        caseAChecks, caseBChecks, caseCChecks);
    result.Data = localReduceData(time, current, voltage, slim, ...
        appliedReactance, deltaD, deltaQ, releaseTimer, ...
        rearmArmed, rearmTimer, sourceVoltageCommand, ...
        transitionIndex);
end

function startTime = localTimerStart( ...
        time, timer, eventTime, confirmTime)
    startTime = NaN;
    if ~isfinite(eventTime)
        return;
    end
    eventIndex = find(time >= eventTime, 1, 'first');
    if isempty(eventIndex)
        return;
    end
    tolerance = max(1e-9, confirmTime*1e-5);
    searchIndex = max(1, eventIndex-1);
    while searchIndex > 1 && timer(searchIndex) > tolerance
        searchIndex = searchIndex-1;
    end
    if searchIndex < eventIndex-1
        startTime = time(searchIndex+1);
    end
end

function signal = localGetSignal(logs, signalName)
    element = logs.get(signalName);
    assert(~isempty(element), ...
        'Required logged signal was not found: %s', signalName);
    signal = element.Values;
end

function values = localInterpolateSignal(signal, queryTime, method)
    sourceTime = double(signal.Time(:));
    sourceData = double(signal.Data(:));
    [sourceTime, uniqueIndex] = unique(sourceTime, 'last');
    sourceData = sourceData(uniqueIndex);
    values = interp1(sourceTime, sourceData, ...
        queryTime, method, 'extrap');
end

function value = localFirstOrNaN(values)
    if isempty(values)
        value = NaN;
    else
        value = values(1);
    end
end

function value = localLastOrNaN(values)
    if isempty(values)
        value = NaN;
    else
        value = values(end);
    end
end

function notes = localCombinedNotes(aChecks, bChecks, cChecks)
    notes = strings(0, 1);
    groups = {aChecks, bChecks, cChecks};
    labels = ["A", "B", "C"];
    for groupIndex = 1:numel(groups)
        names = string(fieldnames(groups{groupIndex}));
        values = struct2cell(groups{groupIndex});
        failed = names(~cellfun(@logical, values));
        if ~isempty(failed)
            notes(end+1, 1) = labels(groupIndex) + ...
                " failed: " + strjoin(failed, '; ');
        end
    end
    if isempty(notes)
        notes = "Passed all automatic checks";
    else
        notes = strjoin(notes, ' | ');
    end
end

function reducedData = localReduceData(time, current, voltage, slim, ...
        appliedReactance, deltaD, deltaQ, releaseTimer, rearmArmed, ...
        rearmTimer, sourceVoltageCommand, transitionIndex)
    maximumPoints = 20000;
    stride = max(1, ceil(numel(time)/maximumPoints));
    keepIndex = (1:stride:numel(time))';
    keepIndex = unique([keepIndex; numel(time); ...
        transitionIndex; transitionIndex-1]);
    keepIndex = keepIndex( ...
        keepIndex >= 1 & keepIndex <= numel(time));

    reducedData = struct();
    reducedData.Time_s = time(keepIndex);
    reducedData.Current_pu = current(keepIndex);
    reducedData.Voltage_pu = voltage(keepIndex);
    reducedData.SourceVoltageCommand_pu = ...
        sourceVoltageCommand(keepIndex);
    reducedData.Slim = slim(keepIndex);
    reducedData.X_vir_applied_pu = appliedReactance(keepIndex);
    reducedData.DeltaUVI_d = deltaD(keepIndex);
    reducedData.DeltaUVI_q = deltaQ(keepIndex);
    reducedData.ReleaseConfirmElapsed_s = releaseTimer(keepIndex);
    reducedData.RearmArmed = rearmArmed(keepIndex);
    reducedData.RearmConfirmElapsed_s = rearmTimer(keepIndex);
end

function result = localEmptyResult()
    result = struct( ...
        'CaseName', "", 'CaseType', "", 'FaultSetting', "", ...
        'SourceSag_pu', NaN, 'GridInductance_H', NaN, ...
        'FaultStartTime', NaN, 'FaultClearTime', NaN, ...
        'VoltageFallTime_s', NaN, ...
        'VoltageRecoveryRampTime_s', NaN, ...
        'ReleaseConfirmTime', NaN, 'RearmConfirmTime', NaN, ...
        'TransitionCount', 0, 'Transitions', table(), ...
        'FirstTriggerTime', NaN, 'FirstExitTime', NaN, ...
        'FinalExitTime', NaN, 'ReleaseConfirmStartTime', NaN, ...
        'RearmConfirmStartTime', NaN, 'FinalRearmTime', NaN, ...
        'PostFaultBoundaryCrossings', 0, 'FinalSlim', NaN, ...
        'FinalVoltage_pu', NaN, 'FinalCurrent_pu', NaN, ...
        'MaximumCurrent_pu', NaN, 'FaultCurrentPeak_pu', NaN, ...
        'LateFaultCurrentMean_pu', NaN, 'Passed', false, ...
        'CaseAPassed', false, 'CaseBPassed', false, ...
        'CaseCPassed', false, 'CaseAChecks', struct(), ...
        'CaseBChecks', struct(), 'CaseCChecks', struct(), ...
        'Notes', "", 'Data', struct());
end

function localPrintTransitions(result)
    fprintf(['\n[%s] sag %.3f p.u.; interface L %.6f H; ' ...
        'confirm %.3f s\n'], ...
        result.CaseName, result.SourceSag_pu, ...
        result.GridInductance_H, result.ReleaseConfirmTime);
    fprintf('Transitions: %d; A/B/C pass: %d/%d/%d\n', ...
        result.TransitionCount, result.CaseAPassed, ...
        result.CaseBPassed, result.CaseCPassed);
    if isempty(result.Transitions)
        fprintf('No Slim transitions.\n');
    else
        disp(result.Transitions);
    end
    fprintf('%s\n', result.Notes);
end

function summaryTable = localBuildSummaryTable(result, gridSource)
    caseName = ["Case A"; "Case B"; "Case C"];
    faultSetting = [ ...
        sprintf('U_PCC = %.3f p.u.; [%.3f, %.3f] s', ...
        gridSource.CaseA.U_PCC_target_pu, ...
        gridSource.CaseA.StartTime_s, gridSource.CaseA.EndTime_s); ...
        sprintf('U_PCC = %.3f p.u.; [%.3f, %.3f] s', ...
        gridSource.CaseB.U_PCC_target_pu, ...
        gridSource.CaseB.StartTime_s, gridSource.CaseB.EndTime_s); ...
        sprintf('U_PCC = %.3f p.u.; [%.3f, %.3f] s', ...
        gridSource.CaseC.U_PCC_target_pu, ...
        gridSource.CaseC.StartTime_s, gridSource.CaseC.EndTime_s)];

    times = result.Transitions.Time_s;
    directions = result.Transitions.Direction;
    transitionCount = [ ...
        nnz(times < gridSource.CaseB.StartTime_s); ...
        nnz(times >= gridSource.CaseB.StartTime_s & ...
        times < gridSource.CaseC.StartTime_s); ...
        result.TransitionCount];
    firstTriggerTime_s = [NaN; result.FirstTriggerTime; ...
        result.FirstTriggerTime];
    finalExitTime_s = [NaN; NaN; result.FinalExitTime];
    releaseConfirmTime_s = repmat(result.ReleaseConfirmTime, 3, 1);
    passed = [result.CaseAPassed; ...
        result.CaseBPassed; result.CaseCPassed];
    notes = [ ...
        "No trigger; Slim remains OFF"; ...
        "One OFF->ON; current falls below Ilim while Slim stays ON"; ...
        "Overall sequence has exactly OFF->ON and ON->OFF"];
    transitionDirections = [ ...
        ""; ...
        strjoin(directions(times >= gridSource.CaseB.StartTime_s & ...
        times < gridSource.CaseC.StartTime_s), ', '); ...
        strjoin(directions, ', ')];

    summaryTable = table(caseName, faultSetting, ...
        transitionCount, transitionDirections, ...
        firstTriggerTime_s, finalExitTime_s, ...
        releaseConfirmTime_s, passed, notes, ...
        'VariableNames', {'CaseName', 'FaultSetting', ...
        'TransitionCount', 'TransitionDirections', ...
        'FirstTriggerTime_s', 'FinalExitTime_s', ...
        'ReleaseConfirmTime_s', 'Passed', 'Notes'});
end
