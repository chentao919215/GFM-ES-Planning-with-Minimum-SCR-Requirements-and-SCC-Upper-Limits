%% GFM 虚拟阻抗限流状态验证
% 独立运行正式参数和正式模型，在同一次 0-6 s 仿真中依次验证：
% Case A（未触发）、Case B（触发并锁存）和 Case C（恢复退出）。
% 扫描 5/10/20 ms 连续恢复/重新武装确认时间，并输出 PNG、MAT、CSV。
% 本脚本不复制模型、不修改拓扑，也不重复定义 GFM 电气参数。

validationScript = mfilename('fullpath');
outputDir = fileparts(validationScript);
projectRoot = outputDir;
for validationLevel = 1:5
    projectRoot = fileparts(projectRoot);
end

modelFile = fullfile(projectRoot, 'simulink', 'models', ...
    'Grid_Forming_Inverters.slx');
parameterFile = fullfile(projectRoot, 'code', 'scripts', 'equipment', ...
    'GFM', 'GFM_Parameters.m');
figureScriptDir = fullfile(projectRoot, 'code', 'scripts', 'figure', ...
    'for_report', 'report_05');

assert(isfile(modelFile), 'GFM model was not found: %s', modelFile);
assert(isfile(parameterFile), ...
    'Formal GFM parameter script was not found: %s', parameterFile);
addpath(fullfile(projectRoot, 'code', 'functions', 'equipment'));
addpath(fullfile(projectRoot, 'code', 'scripts', 'equipment', 'GFM'));
addpath(figureScriptDir);
run(parameterFile);
assert(exist('GFM_VI_State_Validation_Plot', 'file') == 2, ...
    'Independent state-validation plot function was not found.');

modelName = 'Grid_Forming_Inverters';
load_system(modelFile);
sourceBlock = [modelName '/Three-Phase Source'];
interfaceBlock = [modelName ...
    '/GFM_1/Three-Phase PCC Coupling Interface'];
assert(getSimulinkBlockHandle(sourceBlock) > 0, ...
    'The formal programmable three-phase source was not found.');
assert(getSimulinkBlockHandle(interfaceBlock) > 0, ...
    'The converter-side PCC coupling interface was not found.');
assert(strcmp(get_param(interfaceBlock, 'Resistance'), ...
    'GFM_PCC_Interface.R_ohm') && ...
    strcmp(get_param(interfaceBlock, 'Inductance'), ...
    'GFM_PCC_Interface.L_H'), ...
    'The PCC coupling-interface block is not linked to formal parameters.');

confirmCandidates = [0.005, 0.010, 0.020];
scanResults = repmat(localEmptyResult(), numel(confirmCandidates), 1);

fprintf('\n=== GFM sequential state validation ===\n');
fprintf('Model: %s\n', modelFile);
fprintf(['PCC interface: R=%.6f ohm (%.6f p.u.), ' ...
    'L=%.9f H (X=%.6f p.u.).\n'], ...
    GFM_PCC_Interface.R_ohm, GFM_PCC_Interface.R_pu, ...
    GFM_PCC_Interface.L_H, GFM_PCC_Interface.X_pu);
fprintf('PCC command: %.3f -> %.3f -> %.3f p.u.\n', ...
    GFM_GridSource.CaseA.U_PCC_target_pu, ...
    GFM_GridSource.CaseB.U_PCC_target_pu, ...
    GFM_GridSource.CaseC.U_PCC_target_pu);
fprintf('Ub=%.6f p.u.; Ilim=%.6f p.u.; Xvir=%.6f p.u.\n', ...
    GFM_VI.U_boundary_pu, GFM_VI.I_switch_threshold_pu, ...
    GFM_VI.X_vir_device_pu);

for candidateIndex = 1:numel(confirmCandidates)
    confirmTime = confirmCandidates(candidateIndex);
    simulationOutput = localRunFormalSequence( ...
        modelName, confirmTime, GFM_VI, GFM_Sim.t_stop);
    scanResults(candidateIndex) = localAnalyzeFormalSequence( ...
        simulationOutput, confirmTime, GFM_GridSource, GFM_VI, ...
        GFM_PCC_Interface);
    localPrintTransitions(scanResults(candidateIndex));
end

selectedIndex = find([scanResults.Passed], 1, 'first');
if isempty(selectedIndex)
    [~, plotIndex] = min([scanResults.TransitionCount]);
    selectedConfirmTime = NaN;
    selectionNote = [ ...
        "No tested confirmation time passed all checks. " ...
        "The scan stopped at 20 ms."];
else
    plotIndex = selectedIndex;
    selectedConfirmTime = confirmCandidates(selectedIndex);
    selectionNote = sprintf( ...
        'Shortest passing confirmation time: %.3f s.', ...
        selectedConfirmTime);
end

plotResult = scanResults(plotIndex);
summaryTable = localBuildSummaryTable(plotResult, GFM_GridSource);
pngFile = fullfile(outputDir, 'GFM_VI_State_Validation.png');
resultFile = fullfile(outputDir, ...
    'GFM_VI_State_Validation_Result.mat');
summaryFile = fullfile(outputDir, ...
    'GFM_VI_State_Validation_Summary.csv');

GFM_VI_State_Validation_Plot(plotResult, pngFile, ...
    GFM_VI.U_boundary_pu, GFM_VI.I_switch_threshold_pu, ...
    selectedConfirmTime);

ValidationResult = struct();
ValidationResult.GeneratedAt = datetime('now', ...
    'TimeZone', 'Asia/Shanghai');
ValidationResult.ModelFile = modelFile;
ValidationResult.ParameterFile = parameterFile;
ValidationResult.ValidationTopology = [ ...
