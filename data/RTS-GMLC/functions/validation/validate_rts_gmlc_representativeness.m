function Validation = validate_rts_gmlc_representativeness( ...
    Data, Typical_Day_Sets, Wind_Scenario_Sets, Config)
%% 评价固定极端medoid典型日和统一K的RT风电场景代表性
% 典型日使用DA风电，风电场景使用RT风电；二者分别与对应的365日原始
% 统计比较。所有爬坡只取日内23个相邻小时差分，绝不跨日拼接。

wind_to_load_base = Data.Normalization.Wind_System_Capacity_MW / ...
    Data.Normalization.Load_System_Base_MW;

%% 1. 原始365日全年统计量
Original_Typical_Metrics = compute_weighted_profile_metrics( ...
    Data.Daily.System_Load_Normalized, ...
    Data.Daily.Wind_DA_System_Normalized, ...
    ones(numel(Data.Dates), 1), wind_to_load_base);
Original_Scenario_Metrics = compute_weighted_profile_metrics( ...
    Data.Daily.System_Load_Normalized, ...
    Data.Daily.Wind_RT_System_Normalized, ...
    ones(numel(Data.Dates), 1), wind_to_load_base);

%% 2. 各D对应典型日的统计量、聚类误差与极端保持
Typical_Metric_Tables = cell(numel(Typical_Day_Sets), 1);
Typical_Error_Rows = cell(numel(Typical_Day_Sets), 1);
Extreme_Rows = cell(numel(Typical_Day_Sets), 1);
Annual_Stat_Rows = cell(numel(Typical_Day_Sets) + ...
    numel(Wind_Scenario_Sets), 1);
Annual_Stat_Row = 0;
for i_D = 1:numel(Typical_Day_Sets)
    Typical = Typical_Day_Sets(i_D);
    Compressed_Metrics = compute_weighted_profile_metrics( ...
        Typical.System_Load_Normalized, ...
        Typical.Wind_DA_System_Normalized, ...
        Typical.Weight_Days, wind_to_load_base);
    Comparison = compare_metric_tables(Original_Typical_Metrics, ...
        Compressed_Metrics, "typical_day", Typical.D, NaN);
    Typical_Metric_Tables{i_D} = Comparison;
    Annual_Stat_Row = Annual_Stat_Row + 1;
    Annual_Stat_Rows{Annual_Stat_Row} = summarize_metric_errors(Comparison);

    E = Typical.Cluster_Error;
    Typical_Error_Rows{i_D} = table(Typical.D, ...
        Typical.Forced_Extreme_Medoid_Count, ...
        E.SSE_Standardized, E.Mean_Euclidean_Standardized, ...
        E.RMSE_Per_Standardized_Feature, ...
        E.Load_Trajectory_RMSE_Normalized, ...
        E.Wind_DA_Trajectory_RMSE_Normalized, ...
        E.DA_Net_Load_Trajectory_RMSE_Normalized, ...
        Typical.Constrained_PAM.Best_Replicate, ...
        Typical.Constrained_PAM.Best_Swap_Iteration_Count, ...
        'VariableNames', {'D', 'FixedExtremeMedoidCount', ...
        'SSE_Standardized', 'Mean_Euclidean_Standardized', ...
        'RMSE_Per_Standardized_Feature', ...
        'Load_Trajectory_RMSE_Normalized', ...
        'Wind_DA_Trajectory_RMSE_Normalized', ...
        'DA_Net_Load_Trajectory_RMSE_Normalized', ...
        'BestReplicate', 'BestSwapIterationCount'});
    Extreme_Rows{i_D} = validate_extreme_preservation( ...
        Typical, wind_to_load_base, Config);
end

%% 3. 各D/K组合的场景可用性、统计量和重构误差
Scenario_Metric_Tables = cell(numel(Wind_Scenario_Sets), 1);
Scenario_Error_Rows = cell(numel(Wind_Scenario_Sets), 1);
Availability_Rows = cell(numel(Wind_Scenario_Sets), 1);
Available_Metric_Count = 0;
Row_Index = 0;
for i_D = 1:size(Wind_Scenario_Sets, 1)
    Typical = Typical_Day_Sets(i_D);
    for i_K = 1:size(Wind_Scenario_Sets, 2)
        Scenario = Wind_Scenario_Sets(i_D, i_K);
        Row_Index = Row_Index + 1;
        Meets_Member_Requirement = ...
            Scenario.Minimum_Typical_Day_Member_Count >= Scenario.K;
        Availability_Rows{Row_Index} = table( ...
            Scenario.D, Scenario.K, Scenario.Available, ...
            Scenario.Minimum_Typical_Day_Member_Count, Scenario.K, ...
            Meets_Member_Requirement, ...
            string(Scenario.Unavailable_Reason), ...
            'VariableNames', {'D', 'K', 'Available', ...
            'MinimumTypicalDayMemberCount', 'RequiredK', ...
            'AllTypicalDaysMeetK', 'UnavailableReason'});

        if Scenario.Available
            [load_profiles, wind_profiles, profile_weights] = ...
                flatten_scenario_profiles(Typical, Scenario);
            Compressed_Metrics = compute_weighted_profile_metrics( ...
                load_profiles, wind_profiles, profile_weights, ...
                wind_to_load_base);
            Comparison = compare_metric_tables(Original_Scenario_Metrics, ...
                Compressed_Metrics, "wind_scenario", ...
                Scenario.D, Scenario.K);
            Available_Metric_Count = Available_Metric_Count + 1;
            Scenario_Metric_Tables{Available_Metric_Count} = Comparison;
            Annual_Stat_Row = Annual_Stat_Row + 1;
            Annual_Stat_Rows{Annual_Stat_Row} = ...
                summarize_metric_errors(Comparison);
        end

        E = Scenario.Error;
        Scenario_Error_Rows{Row_Index} = table( ...
            Scenario.D, Scenario.K, Scenario.Available, ...
            Scenario.Minimum_Typical_Day_Member_Count, ...
            E.Cluster_RMSE_Overall, ...
            E.Wind_Reconstruction_RMSE_Overall, ...
            E.Wind_Reconstruction_MAE_Overall, ...
            string(Scenario.Unavailable_Reason), ...
            'VariableNames', {'D', 'K', 'Available', ...
            'MinimumTypicalDayMemberCount', ...
            'Wind_RT_Cluster_RMSE_Normalized', ...
            'Wind_RT_Reconstruction_RMSE_Normalized', ...
            'Wind_RT_Reconstruction_MAE_Normalized', ...
            'UnavailableReason'});
    end
end

Validation = struct();
Validation.Definition = struct();
Validation.Definition.Typical_Day_Wind_Basis = ...
    '日前风电预测；用于负荷+日前风电联合典型日压缩';
Validation.Definition.Typical_Day_Construction = ...
    'D为最终典型日总数；最大/最小日前净负荷日为固定medoid，其余D-2个中心由受约束PAM选择，全年365天分配至最近中心';
Validation.Definition.Wind_Scenario_Wind_Basis = ...
    '每个典型日全部成员的系统聚合归一化RT实际风电小时均值；可用组合内所有典型日统一使用K条medoid轨迹';
Validation.Definition.Net_Load = ...
    '负荷标幺值 - 风电容量因子×(风电总装机MW/全年峰值负荷MW)';
Validation.Definition.Ramp = ...
    '仅统计同一自然日内相邻小时的23个爬坡，不拼接不同自然日';
Validation.Original_Typical_Day_Metrics = Original_Typical_Metrics;
Validation.Original_Wind_Scenario_Metrics = Original_Scenario_Metrics;
Validation.Typical_Day_Metrics = vertcat(Typical_Metric_Tables{:});
Validation.Typical_Day_Cluster_Error = vertcat(Typical_Error_Rows{:});
Validation.Extreme_Day_Preservation = vertcat(Extreme_Rows{:});
if Available_Metric_Count > 0
    Validation.Wind_Scenario_Metrics = vertcat( ...
        Scenario_Metric_Tables{1:Available_Metric_Count});
else
    Validation.Wind_Scenario_Metrics = table();
end
Validation.Wind_Scenario_Availability = vertcat(Availability_Rows{:});
Validation.Wind_Scenario_Error = vertcat(Scenario_Error_Rows{:});
Validation.Annual_Statistic_Reconstruction_Error = ...
    vertcat(Annual_Stat_Rows{1:Annual_Stat_Row});

end

%% 4. 本地函数：极端日前净负荷保持
function Preservation = validate_extreme_preservation( ...
    Typical, Wind_To_Load_Base, Config)
%% 核验最大、最小净负荷极端日被原样保留。
Net_Load = Typical.System_Load_Normalized - ...
    Typical.Wind_DA_System_Normalized * Wind_To_Load_Base;
[maximum_value, maximum_linear_index] = max(Net_Load, [], 'all');
[minimum_value, minimum_linear_index] = min(Net_Load, [], 'all');
[maximum_typical_day, maximum_hour] = ind2sub( ...
    size(Net_Load), maximum_linear_index);
[minimum_typical_day, minimum_hour] = ind2sub( ...
    size(Net_Load), minimum_linear_index);
E = Typical.Extreme_Days;
Maximum_Value_Error = abs(maximum_value - E.Maximum_Value);
Minimum_Value_Error = abs(minimum_value - E.Minimum_Value);
Maximum_Medoid_Position = find( ...
    Typical.Medoid_Day_Index == E.Maximum_Day_Index, 1);
Minimum_Medoid_Position = find( ...
    Typical.Medoid_Day_Index == E.Minimum_Day_Index, 1);
Maximum_Date_Retained = ~isempty(Maximum_Medoid_Position);
Minimum_Date_Retained = ~isempty(Minimum_Medoid_Position);
Maximum_Preserved = Maximum_Date_Retained && ...
    Maximum_Value_Error <= Config.Numeric_Tolerance;
Minimum_Preserved = Minimum_Date_Retained && ...
    Minimum_Value_Error <= Config.Numeric_Tolerance;
if ~(Maximum_Preserved && Minimum_Preserved)
    error('RTS_GMLC:ExtremeDayPreservationFailure', ...
        'D=%d未精确保留最大/最小日前净负荷固定medoid。', Typical.D);
end
Preservation = table(Typical.D, ...
    E.Maximum_Date, E.Maximum_Hour, E.Maximum_Value, ...
    Typical.Medoid_Date(maximum_typical_day), maximum_hour, ...
    maximum_value, Maximum_Value_Error, Maximum_Date_Retained, ...
    Maximum_Preserved, Typical.Weight_Days(Maximum_Medoid_Position), ...
    E.Minimum_Date, E.Minimum_Hour, E.Minimum_Value, ...
    Typical.Medoid_Date(minimum_typical_day), minimum_hour, ...
    minimum_value, Minimum_Value_Error, Minimum_Date_Retained, ...
    Minimum_Preserved, Typical.Weight_Days(Minimum_Medoid_Position), ...
    'VariableNames', {'D', 'MaximumOriginalDate', ...
    'MaximumOriginalHour', 'MaximumOriginalValue', ...
    'MaximumRepresentativeDate', 'MaximumRepresentativeHour', ...
    'MaximumRepresentativeValue', 'MaximumValueError', ...
    'MaximumFixedMedoidRetained', 'MaximumPreserved', ...
    'MaximumMedoidWeightDays', 'MinimumOriginalDate', ...
    'MinimumOriginalHour', 'MinimumOriginalValue', ...
    'MinimumRepresentativeDate', 'MinimumRepresentativeHour', ...
    'MinimumRepresentativeValue', 'MinimumValueError', ...
    'MinimumFixedMedoidRetained', 'MinimumPreserved', ...
    'MinimumMedoidWeightDays'});
end

%% 1. 本地函数：年度统计误差摘要
function Summary = summarize_metric_errors(Comparison)
%% 汇总代表曲线与全年数据的各项统计偏差。
Key_Metrics = ["Average_Load", "Peak_Load", ...
    "Average_Wind_Capacity_Factor", "Peak_Net_Load"];
Key_Rows = ismember(Comparison.Metric, Key_Metrics);
Summary = table(Comparison.CompressionType(1), Comparison.D(1), ...
    Comparison.K(1), mean(Comparison.AbsoluteError), ...
    max(Comparison.AbsoluteError), mean(Comparison.RelativeErrorPercent), ...
    max(Comparison.RelativeErrorPercent), ...
    mean(Comparison.RelativeErrorPercent(Key_Rows)), ...
    max(Comparison.RelativeErrorPercent(Key_Rows)), ...
    'VariableNames', {'CompressionType', 'D', 'K', ...
    'MeanAbsoluteErrorAllMetrics', 'MaximumAbsoluteErrorAllMetrics', ...
    'MeanRelativeErrorPercentAllMetrics', ...
    'MaximumRelativeErrorPercentAllMetrics', ...
    'MeanRelativeErrorPercentKeyMetrics', ...
    'MaximumRelativeErrorPercentKeyMetrics'});
end

function Metrics = compute_weighted_profile_metrics( ...
    Load_Profile, Wind_Profile, Profile_Weight, Wind_To_Load_Base)
% Profile为[代表曲线, hour]；Profile_Weight可为天数或“天数×场景概率”。
if ~isequal(size(Load_Profile), size(Wind_Profile)) || ...
        size(Load_Profile, 1) ~= numel(Profile_Weight)
    error('RTS_GMLC:ValidationProfileDimensionMismatch', ...
        '代表性指标输入曲线与权重维度不一致。');
end
Profile_Weight = Profile_Weight(:);
if any(~isfinite(Profile_Weight)) || any(Profile_Weight < 0) || ...
        sum(Profile_Weight) <= 0
    error('RTS_GMLC:InvalidValidationWeights', ...
        '代表性指标权重必须为有限非负数且总和为正。');
end

Net_Load_Profile = Load_Profile - Wind_Profile * Wind_To_Load_Base;
Ramp_Suffix = ["Ramp_Mean_Absolute"; "Ramp_P95_Absolute"; ...
    "Ramp_Maximum_Up"; "Ramp_Maximum_Down_Magnitude"];
metric = ["Average_Load"; "Peak_Load"; ...
    "Average_Wind_Capacity_Factor"; "Peak_Net_Load"; ...
    "Load_" + Ramp_Suffix; "Wind_" + Ramp_Suffix; ...
    "Net_Load_" + Ramp_Suffix];
unit = ["p.u._of_annual_peak_load"; "p.u._of_annual_peak_load"; ...
    "p.u._of_wind_capacity"; "p.u._of_annual_peak_load"; ...
    repmat("p.u._of_annual_peak_load_per_h", 4, 1); ...
    repmat("p.u._of_wind_capacity_per_h", 4, 1); ...
    repmat("p.u._of_annual_peak_load_per_h", 4, 1)];
value = [weighted_profile_mean(Load_Profile, Profile_Weight); ...
    max(Load_Profile, [], 'all'); ...
    weighted_profile_mean(Wind_Profile, Profile_Weight); ...
    max(Net_Load_Profile, [], 'all'); ...
    compute_ramp_metrics(Load_Profile, Profile_Weight); ...
    compute_ramp_metrics(Wind_Profile, Profile_Weight); ...
    compute_ramp_metrics(Net_Load_Profile, Profile_Weight)];
Metrics = table(metric, unit, value, ...
    'VariableNames', {'Metric', 'Unit', 'Value'});
end

function Values = compute_ramp_metrics(Profile, Profile_Weight)
% 四项顺序固定为：平均绝对值、绝对值P95、最大上爬坡、最大下爬坡幅值。
ramp = diff(Profile, 1, 2);
Ramp_Weight = repmat(Profile_Weight, 1, size(ramp, 2));
valid = Ramp_Weight > 0;
Ramp_Values = ramp(valid);
Weight_Values = Ramp_Weight(valid);
Values = [sum(abs(Ramp_Values) .* Weight_Values) / sum(Weight_Values); ...
    weighted_quantile(abs(Ramp_Values), Weight_Values, 0.95); ...
    max(Ramp_Values); -min(Ramp_Values)];
end

function Mean_Value = weighted_profile_mean(Profile, Profile_Weight)
%% 按典型日权重计算全年代表曲线均值。
Mean_Value = sum(Profile_Weight .* mean(Profile, 2)) / sum(Profile_Weight);
end

function Quantile = weighted_quantile(Values, Weights, Probability)
% 使用左连续加权经验分位数，与复制整数权重样本后的定义一致。
[sorted_values, order] = sort(Values(:));
Sorted_Weights = Weights(order);
Cumulative_Weight = cumsum(Sorted_Weights) / sum(Sorted_Weights);
index = find(Cumulative_Weight >= Probability, 1, 'first');
Quantile = sorted_values(index);
end

function Comparison = compare_metric_tables(Original, Compressed, ...
    Compression_Type, D, K)
%% 按共同指标比较原始数据与代表数据的统计结果。
if ~isequal(Original.Metric, Compressed.Metric) || ...
        ~isequal(Original.Unit, Compressed.Unit)
    error('RTS_GMLC:MetricDefinitionMismatch', ...
        '原始与压缩后指标定义不一致。');
end
Original_Value = Original.Value;
Compressed_Value = Compressed.Value;
Absolute_Error = abs(Compressed_Value - Original_Value);
% 原始值接近0时以eps保护分母，避免无穷大破坏汇总表。
Relative_Error_Percent = 100 * Absolute_Error ./ max(abs(Original_Value), eps);
Row_Count = height(Original);
Comparison = table(repmat(string(Compression_Type), Row_Count, 1), ...
    repmat(D, Row_Count, 1), repmat(K, Row_Count, 1), ...
    Original.Metric, Original.Unit, Original_Value, Compressed_Value, ...
    Absolute_Error, Relative_Error_Percent, ...
    'VariableNames', {'CompressionType', 'D', 'K', 'Metric', 'Unit', ...
    'OriginalValue', 'CompressedValue', 'AbsoluteError', ...
    'RelativeErrorPercent'});
end

function [Load_Profile, Wind_Profile, Profile_Weight] = ...
    flatten_scenario_profiles(Typical, Scenario)
% 展平后每条组合曲线权重=典型日成员天数×该典型日内部场景概率。
D = Scenario.D;
K = Scenario.K;
T = size(Typical.System_Load_Normalized, 2);
Load_Profile = zeros(D * K, T);
Wind_Profile = zeros(D * K, T);
Profile_Weight = zeros(D * K, 1);
row = 0;
for d = 1:D
    for k = 1:K
        row = row + 1;
        Load_Profile(row, :) = Typical.System_Load_Normalized(d, :);
        Wind_Profile(row, :) = reshape( ...
            Scenario.Wind_Scenario_Normalized(d, k, :), 1, T);
        Profile_Weight(row) = Typical.Weight_Days(d) * ...
            Scenario.Probability(d, k);
    end
end
if abs(sum(Profile_Weight) - sum(Typical.Weight_Days)) > 1e-10
    error('RTS_GMLC:FlattenedScenarioWeightMismatch', ...
        '场景展平后的权重和与典型日权重和不一致。');
end
end
