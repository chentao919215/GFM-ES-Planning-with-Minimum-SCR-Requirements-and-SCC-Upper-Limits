function [Result, Output] = save_rts_gmlc_preprocessing_results( ...
    Data, Typical_Day_Sets, Wind_Scenario_Sets, Validation, Config)
%% 保存规划输入、来源信息和少量可读表格。
% 年度数组和重复平面表仅用于预处理计算，不写入最终MAT。
% 每次重新生成使用独立目录，processed中的Manuscript输入由人工核对后更新。

%% 1. 保留规划输入及其来源和质量记录
Result = struct();
Result.Metadata = struct( ...
    'Schema_Version', 1, ...
    'Generated_At', datetime('now', 'TimeZone', 'Asia/Shanghai'), ...
    'Source_Repository', Config.Source.Repository, ...
    'Source_Version', Config.Source.Version, ...
    'Source_Commit', Config.Source.Commit, ...
    'Random_Seed', Config.Random_Seed, ...
    'IEEE30_Capacity_Mapping_Applied', false);
Result.Dimensions = struct( ...
    'Valid_Day_Count', numel(Data.Dates), ...
    'Period_Count', Config.Period_Count, ...
    'Period_Duration_Hours', Config.Period_Duration_Hours, ...
    'D_Values', Config.D_Values, 'K_Values', Config.K_Values, ...
    'Forced_Extreme_Day_Count', Config.Forced_Extreme_Day_Count);
Result.Source_Manifest = Data.Source_Manifest;
Result.Normalization = Data.Normalization;
Result.Calendar = Data.Calendar;
Result.Typical_Day_Sets = Typical_Day_Sets;
Result.Wind_Scenario_Sets = Wind_Scenario_Sets;
Result.Validation = Validation;
Result.Quality_Checks = [Data.Quality_Checks; ...
    validate_result(Data, Result, Config)];

% IEEE-30使用自身的节点负荷分布，仅需RTS-GMLC的系统归一化曲线。
Result.Typical_Day_Sets = rmfield(Result.Typical_Day_Sets, ...
    {'Node_Load_Normalized', 'Wind_DA_Site_Normalized', 'Wind_RT_Site_Normalized'});
for d = 1:numel(Result.Typical_Day_Sets)
    Result.Typical_Day_Sets(d).Dimensions = ...
        struct('System_Profile', {{'typical_day', 'hour'}});
end

%% 2. 保存精简MAT及四张审阅表
Timestamp = char(datetime('now', 'Format', 'yyyyMMdd_HHmmss'));
Run_Directory = fullfile(Config.Output.Root, ['run_', Timestamp]);
if isfolder(Run_Directory)
    error('RTS_GMLC:ExistingRunDirectory', '结果目录已存在：%s', Run_Directory);
end
[Success, Message] = mkdir(Run_Directory);
if ~Success
    error('RTS_GMLC:CreateDirectoryFailure', '无法创建结果目录：%s', Message);
end
MAT_File = fullfile(Run_Directory, 'rts_gmlc_profiles.mat');
save(MAT_File, 'Result', '-v7');

[Typical_Table, Scenario_Table] = build_profile_tables(Result);
Tables = {Result.Source_Manifest, Typical_Table, ...
    Scenario_Table, Result.Quality_Checks};
Names = {'source_manifest.csv', 'typical_day_profiles.csv', ...
    'wind_scenario_profiles.csv', 'quality_checks.csv'};
CSV_Files = cell(size(Names));
for k = 1:numel(Names)
    CSV_Files{k} = fullfile(Run_Directory, Names{k});
    writetable(Tables{k}, CSV_Files{k});
end
Output = struct('Run_Directory', Run_Directory, ...
    'MAT_File', MAT_File, 'CSV_Files', {CSV_Files});
end

function Checks = validate_result(Data, Result, Config)
%% 检查时间维度、极端日保持、权重及各可用场景的概率和物理边界。
T = Config.Period_Count;
Day_Count = Config.Calendar.Expected_Day_Count;
Dimension_OK = numel(Data.Dates) == Day_Count && ...
    ~any(Data.Dates == Config.Calendar.Excluded_Date) && ...
    isequal(size(Data.Daily.System_Load_Normalized), [Day_Count T]) && ...
    isequal(size(Data.Daily.Wind_DA_System_Normalized), [Day_Count T]) && ...
    isequal(size(Data.Daily.Wind_RT_System_Normalized), [Day_Count T]);
Weight_OK = true;
Extreme_OK = true;
for k = 1:numel(Result.Typical_Day_Sets)
    S = Result.Typical_Day_Sets(k);
    Weight_OK = Weight_OK && all(S.Weight_Days > 0) && ...
        sum(S.Weight_Days) == Day_Count && ...
        isequal(size(S.System_Load_Normalized), [S.D T]) && ...
        isequal(size(S.Wind_DA_System_Normalized), [S.D T]);
    Extreme_OK = Extreme_OK && ...
        S.Medoid_Day_Index(1) == S.Extreme_Days.Maximum_Day_Index && ...
        S.Medoid_Day_Index(2) == S.Extreme_Days.Minimum_Day_Index;
end
Extreme = Result.Validation.Extreme_Day_Preservation;
Extreme_OK = Extreme_OK && all(Extreme.MaximumPreserved & Extreme.MinimumPreserved);
Availability_OK = numel(Result.Wind_Scenario_Sets) == ...
    numel(Config.D_Values)*numel(Config.K_Values);
Probability_OK = true;
Boundary_OK = true;
Scenario_OK = true;
for k = 1:numel(Result.Wind_Scenario_Sets)
    S = Result.Wind_Scenario_Sets(k);
    Availability_OK = Availability_OK && ...
        S.Available == (S.Minimum_Typical_Day_Member_Count >= S.K);
    if ~S.Available
        continue;
    end
    Scenario_OK = Scenario_OK && ...
        isequal(size(S.Probability), [S.D S.K]) && ...
        isequal(size(S.Wind_Scenario_Normalized), [S.D S.K T]) && ...
        isequal(size(S.Scenario_Member_Count), [S.D S.K]) && ...
        all(S.Scenario_Member_Count >= 1, 'all');
    Probability_OK = Probability_OK && all(isfinite(S.Probability), 'all') && ...
        all(S.Probability > 0, 'all') && ...
        all(abs(sum(S.Probability, 2)-1) <= Config.Probability_Tolerance);
    Boundary_OK = Boundary_OK && ...
        all(isfinite(S.Wind_Scenario_Normalized), 'all') && ...
        all(S.Wind_Scenario_Normalized >= -Config.Numeric_Tolerance, 'all') && ...
        all(S.Wind_Scenario_Normalized <= 1+Config.Numeric_Tolerance, 'all');
end
Passed = [Dimension_OK; Weight_OK; Extreme_OK; Availability_OK; ...
    Scenario_OK; Probability_OK; Boundary_OK];
if ~all(Passed)
    error('RTS_GMLC:FinalQualityCheckFailure', ...
        '最终时间维度、权重、极端日、场景可用性、概率或物理边界检查失败。');
end
Check = ["processed_dimensions";"typical_day_weight_sum"; ...
    "fixed_extreme_medoids";"wind_scenario_availability"; ...
    "uniform_k_scenario_dimensions";"scenario_probability_sum"; ...
    "scenario_physical_boundaries"];
Checks = table(Check, string(Passed), repmat("true", numel(Check), 1), Passed, ...
    'VariableNames', {'Check', 'Observed', 'Expected', 'Passed'});
end

function [Typical_Table, Scenario_Table] = build_profile_tables(Result)
%% 每行对应一个小时，便于直接核查归一化曲线、权重和概率。
T = Result.Dimensions.Period_Count;
Typical_Tables = cell(numel(Result.Typical_Day_Sets), 1);
for k = 1:numel(Typical_Tables)
    S = Result.Typical_Day_Sets(k);
    Typical_Tables{k} = table(repmat(S.D, S.D*T, 1), ...
        repelem((1:S.D).', T), repelem(S.Medoid_Date(:), T), ...
        repelem(S.Weight_Days(:), T), repmat((1:T).', S.D, 1), ...
        reshape(S.System_Load_Normalized.', [], 1), ...
        reshape(S.Wind_DA_System_Normalized.', [], 1), ...
        'VariableNames', {'D', 'Typical_Day', 'Medoid_Date', 'Weight_Days', ...
        'Hour', 'Load_Factor', 'Wind_DA_Factor'});
end
Typical_Table = vertcat(Typical_Tables{:});

Scenario_Table = table('Size', [0 7], ...
    'VariableTypes', repmat({'double'}, 1, 7), ...
    'VariableNames', {'D', 'K', 'Typical_Day', 'Scenario', 'Hour', ...
    'Probability', 'Wind_Factor'});
for k = 1:numel(Result.Wind_Scenario_Sets)
    S = Result.Wind_Scenario_Sets(k);
    if ~S.Available
        continue;
    end
    Count = S.D*S.K*T;
    Part = table(repmat(S.D, Count, 1), repmat(S.K, Count, 1), ...
        repelem((1:S.D).', S.K*T), ...
        repmat(repelem((1:S.K).', T), S.D, 1), repmat((1:T).', S.D*S.K, 1), ...
        repelem(reshape(S.Probability.', [], 1), T), ...
        reshape(permute(S.Wind_Scenario_Normalized, [3 2 1]), [], 1), ...
        'VariableNames', Scenario_Table.Properties.VariableNames);
    Scenario_Table = [Scenario_Table; Part]; %#ok<AGROW>
end
end
